-- THE THIRD WAY OUT OF THE CULLING CALCULATOR IS NOW RAISED BY THE PHONE.
--
-- The category and the route have been in the database since
-- RUN_ME_culling_inang.sql was run, and nothing raised them: the register of
-- what the system opens by itself printed
--
--   From Culling Calculator - Request HQ Verification   by hand   Nursery Operation
--
-- because no code anywhere filed a case under it. The calculator had two
-- answers, and the one the table was built for was never written.
--
-- The phone now has it. A block still above ten percent after a SECOND pokok
-- inang selection goes to HQ instead of asking the auditor the same question
-- a second time, and the round count comes off fcportal_culling_inang —
-- which is why that table exists, and why it cannot live on the phone: the
-- second round is usually keyed by somebody else, often on a different one.
--
-- Three parts, and only the second is a change of anything:
--
--   1. The table, its unique index, its policy and its grants, IF NOT
--      EXISTS throughout. Already there if RUN_ME_culling_inang.sql was run
--      in full, and the phone cannot save a round without every one of them
--      -- the upsert names (plot, batch) as its conflict target, so without
--      the INDEX every save after the first is a refused insert.
--
--   2. auto_condition on the category, which is what puts it on Automate
--      Cases. The words are the module code decision written down, the same
--      way the two beside it carry theirs.
--
--   3. The route, re-asserted. HQ Operation, as the office set it.
--
-- Safe to re-run. Changes no case, and seeds no selection: a round nobody
-- counted is not a round, so every block starts where it stands.
-- Run in Supabase SQL Editor (main project: kibqjztozokohqmhqqqf).
-- ============================================================================

-- ── 1. THE TABLE THE ROUND COUNT LIVES IN ───────────────────────
--
-- ONE ROW PER BLOCK of ground, replaced each round rather than added to: the
-- figure that matters is the one standing now, and the round count is what
-- the button is decided from.
CREATE TABLE IF NOT EXISTS public.fcportal_culling_inang (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot          TEXT NOT NULL,
  batch         TEXT NOT NULL DEFAULT '',
  nursery       TEXT,
  qty           INT NOT NULL DEFAULT 0 CHECK (qty >= 0),
  terms         JSONB NOT NULL DEFAULT '[]'::jsonb,
  balance       INT,
  transplant    INT,
  attempt       INT NOT NULL DEFAULT 1 CHECK (attempt >= 1),
  saved_by      TEXT,
  saved_by_id   UUID,
  saved_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS nursery TEXT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS terms JSONB NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS balance INT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS transplant INT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS attempt INT NOT NULL DEFAULT 1;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS saved_by TEXT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS saved_by_id UUID;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS saved_at TIMESTAMPTZ NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS fcportal_culling_inang_block
  ON public.fcportal_culling_inang (plot, batch);

ALTER TABLE public.fcportal_culling_inang ENABLE ROW LEVEL SECURITY;

-- Any signed in account, which is what the FC Portal is. The row says who
-- saved it, so a selection is attributable without being restricted.
DROP POLICY IF EXISTS fcportal_culling_inang_staff ON public.fcportal_culling_inang;
CREATE POLICY fcportal_culling_inang_staff ON public.fcportal_culling_inang
  FOR ALL TO authenticated
  USING (auth.uid() IS NOT NULL)
  WITH CHECK (auth.uid() IS NOT NULL);

-- DELETE is in the list because the phone clears a block that has left the
-- calculator: a plot whose collecting status has closed, or whose drone map
-- has landed, has been dealt with, and last month selection against it is a
-- round count waiting to send the next season straight to HQ.
GRANT SELECT, INSERT, UPDATE, DELETE ON public.fcportal_culling_inang TO authenticated;


-- ── 2. WHAT RAISES IT, AND 3. WHERE IT GOES ─────────────────────
--
-- Through EXECUTE, because this database may not carry every earlier Nelos
-- migration and a plain statement naming a column that is not there fails at
-- PARSE time, before any guard can run.
DO $hq$
DECLARE
  cat_name   CONSTANT TEXT := 'From Culling Calculator - Request HQ Verification';
  cond       CONSTANT TEXT :=
    'The culling calculator puts a plot above 10% again after a second pokok inang '
    'selection, and the Field Conductor presses "Request HQ verification"';
  has_cats   BOOLEAN := to_regclass('public.nelos_categories') IS NOT NULL;
  has_routes BOOLEAN := to_regclass('public.nelos_routes')     IS NOT NULL;
  has_modkey BOOLEAN := EXISTS (SELECT 1 FROM information_schema.columns
                                 WHERE table_schema='public' AND table_name='nelos_categories'
                                   AND column_name='module_key');
  has_auto   BOOLEAN := EXISTS (SELECT 1 FROM information_schema.columns
                                 WHERE table_schema='public' AND table_name='nelos_categories'
                                   AND column_name='auto_condition');
  has_scan   BOOLEAN := false;
  has_hq     BOOLEAN := false;
  n          INT;
BEGIN
  IF to_regclass('public.nelos_modules') IS NOT NULL THEN
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_modules WHERE key='scan') $q$ INTO has_scan;
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_modules WHERE key='nursery_ops') $q$ INTO has_hq;
  END IF;

  -- The row itself, for a database that never had RUN_ME_culling_inang.sql.
  IF NOT has_cats THEN
    RAISE NOTICE '2. SKIPPED -- no nelos_categories table.';
  ELSIF has_modkey THEN
    EXECUTE format($q$
      INSERT INTO public.nelos_categories (name, module_key, sort_order, default_priority)
      SELECT %L, 'scan', 54, 'normal'
       WHERE NOT EXISTS (SELECT 1 FROM public.nelos_categories
                          WHERE module_key='scan' AND lower(name)=lower(%L))
    $q$, cat_name, cat_name);
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE '2. Category under FC Portal: % row(s) added.', n;
  END IF;

  -- What raises it. OVERWRITTEN rather than filled in only where empty: the
  -- old wording was the remark of a feature nobody had built, and what the
  -- phone now does is the thing this column is for. A condition that
  -- disagrees with the code is worse than none, because the page reads as
  -- though somebody checked it.
  IF NOT has_auto THEN
    RAISE NOTICE '2b. SKIPPED -- nelos_categories has no auto_condition column. Run migration_nelos_auto_conditions.sql first.';
  ELSE
    EXECUTE format($q$
      UPDATE public.nelos_categories
         SET auto_condition = %L
       WHERE lower(name) = lower(%L)
         AND COALESCE(auto_condition, '') <> %L
    $q$, cond, cat_name, cond);
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE '2b. Marked as raised by the system: % row(s).', n;
  END IF;

  -- Where it goes. HQ Operation, as the office set it.
  IF NOT has_routes THEN
    RAISE NOTICE '3. SKIPPED -- no nelos_routes table.';
  ELSIF NOT (has_scan AND has_hq) THEN
    RAISE NOTICE '3. SKIPPED -- nelos_modules is missing scan and/or nursery_ops.';
  ELSE
    EXECUTE format($q$
      INSERT INTO public.nelos_routes (source_module, category, to_module)
      SELECT 'scan', %L, 'nursery_ops'
       WHERE NOT EXISTS (SELECT 1 FROM public.nelos_routes
                          WHERE source_module='scan' AND category=%L)
    $q$, cat_name, cat_name);
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE '3. FC Portal plus HQ Verification to HQ Operation: % row(s) added.', n;
  END IF;
END $hq$;


-- ── THE ANSWER, WORKED OUT BEFORE THE QUERY NAMES IT ────────────
--
-- A plain SELECT naming nelos_routes or the selection table is parsed
-- whether or not it is there, and a CASE guarding it does not help: the
-- parse fails first and takes the whole file with it. This has cost a paste
-- before. So each answer is worked out here, into a session setting, and the
-- query below names no table that might not exist.
DO $verdict$
DECLARE
  ok_cat   BOOLEAN := false;
  ok_route BOOLEAN := false;
  ok_tbl   BOOLEAN := to_regclass('public.fcportal_culling_inang') IS NOT NULL;
  ok_idx   BOOLEAN := EXISTS (SELECT 1 FROM pg_class WHERE relname='fcportal_culling_inang_block');
  rounds   INT := 0;
BEGIN
  IF to_regclass('public.nelos_categories') IS NOT NULL THEN
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_categories
                                WHERE lower(name)=lower('From Culling Calculator - Request HQ Verification')
                                  AND auto_condition IS NOT NULL) $q$ INTO ok_cat;
  END IF;
  IF to_regclass('public.nelos_routes') IS NOT NULL THEN
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_routes
                                WHERE source_module='scan'
                                  AND category='From Culling Calculator - Request HQ Verification'
                                  AND to_module='nursery_ops') $q$ INTO ok_route;
  END IF;
  IF ok_tbl THEN
    EXECUTE $q$ SELECT count(*) FROM public.fcportal_culling_inang $q$ INTO rounds;
  END IF;
  PERFORM set_config('mjm.hq_cat',   CASE WHEN ok_cat   THEN 'OK' ELSE 'NOT OK' END, false);
  PERFORM set_config('mjm.hq_route', CASE WHEN ok_route THEN 'OK' ELSE 'NOT OK' END, false);
  PERFORM set_config('mjm.hq_tbl',   CASE WHEN ok_tbl AND ok_idx THEN 'OK' ELSE 'NOT OK' END, false);
  PERFORM set_config('mjm.hq_rows',  rounds::TEXT, false);
END $verdict$;


-- ── WHAT A GOOD RESULT LOOKS LIKE ───────────────────────────────
--
-- Four rows, and every one of them should read OK.
--
--   1 table      the table and its unique index. Without the index every
--                save after the first round is refused
--   2 automatic  the category now carries what raises it, so it appears on
--                Automate Cases beside the other two culling titles
--   3 route      FC Portal plus this title goes to HQ Operation
--   4 rounds     how many blocks have a selection recorded. NOUGHT is the
--                right answer today and is marked OK for that reason:
--                nothing is seeded, so the first block to be counted twice
--                after this is the first one that can reach HQ
SELECT '1 table'     AS part, current_setting('mjm.hq_tbl',   true) AS result,
       'the round count has somewhere to live'                      AS means
UNION ALL
SELECT '2 automatic', current_setting('mjm.hq_cat',   true),
       'on Automate Cases as something the system opens by itself'
UNION ALL
SELECT '3 route',     current_setting('mjm.hq_route', true),
       'FC Portal plus HQ Verification goes to HQ Operation'
UNION ALL
SELECT '4 rounds',    'OK',
       current_setting('mjm.hq_rows', true) || ' block(s) have a selection recorded so far'
ORDER BY part;
