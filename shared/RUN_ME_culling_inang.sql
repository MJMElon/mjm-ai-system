-- ============================================================================
-- MJM AI POWERED SYSTEM — RUN_ME_culling_inang.sql
--
-- THE CULLING CALCULATOR KEEPS ITS POKOK INANG SELECTION, AND HQ IS THE
-- THIRD WAY OUT.
--
-- Two things, and they are one change:
--
--   1. fcportal_culling_inang — what the Field Conductor selected out of each
--      block, and WHICH ROUND it was saved on. The round is the point: a plot
--      still over ten percent after a second selection is one HQ comes and
--      looks at, and no phone can answer how many rounds a plot has had,
--      because the second round is usually keyed by somebody else and often
--      on a different phone.
--
--   2. The Nelos category and route for that third button, pointed at HQ
--      Operation. A case carries its category BY VALUE and nelos_routes
--      matches on that string, so the words here, the words in the category
--      row and the words in cullingActions.js are three spellings of ONE
--      string. Change any of them alone and every HQ verification falls back
--      to the Field Conductor who raised it.
--
-- ONE ROW PER BLOCK of ground, replaced each round rather than added to: the
-- figure that matters is the one standing now, and the round count is what
-- the button is decided from.
--
-- IT CLEARS ITSELF. A plot is on the calculator because a PALMS collecting
-- status is open on it. Once that closes, the plot has been collected and
-- last month selection against it is a figure waiting to be mistaken for a
-- current one. The PHONE does the clearing, because the calculator is the
-- one thing that knows the live list, and it only ever deletes against a
-- list it read from the server -- never against a cached one, which would
-- wipe every plot opened since. A leftover row is harmless in the meantime:
-- it is only ever read for a plot that IS on the list.
--
-- Run in the Supabase SQL Editor. Safe to run twice.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.fcportal_culling_inang (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot          TEXT NOT NULL,
  batch         TEXT NOT NULL DEFAULT '',
  nursery       TEXT,
  qty           INT NOT NULL DEFAULT 0 CHECK (qty >= 0),
  terms         JSONB NOT NULL DEFAULT '[]'::jsonb,
  balance       INT,
  transplant    INT,
  attempt       INT NOT NULL DEFAULT 1 CHECK (attempt >= 1),
  saved_by      TEXT,
  saved_by_id   UUID,
  saved_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS nursery TEXT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS terms JSONB NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS balance INT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS transplant INT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS saved_by TEXT;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS saved_by_id UUID;
ALTER TABLE public.fcportal_culling_inang ADD COLUMN IF NOT EXISTS saved_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- The upsert the phone sends names (plot, batch) as its conflict target, so
-- this index is not a nicety: without it every save after the first is a
-- refused insert.
CREATE UNIQUE INDEX IF NOT EXISTS fcportal_culling_inang_block
  ON public.fcportal_culling_inang (plot, batch);

ALTER TABLE public.fcportal_culling_inang ENABLE ROW LEVEL SECURITY;

-- Any signed in account, which is what the FC Portal is: it is entered with
-- a Supabase account, and every Field Conductor who can open the calculator
-- is meant to be able to record what they counted. The row says who saved
-- it, so a selection is attributable without being restricted.
DROP POLICY IF EXISTS fcportal_culling_inang_staff ON public.fcportal_culling_inang;
CREATE POLICY fcportal_culling_inang_staff ON public.fcportal_culling_inang
  FOR ALL TO authenticated
  USING (auth.uid() IS NOT NULL)
  WITH CHECK (auth.uid() IS NOT NULL);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.fcportal_culling_inang TO authenticated;

NOTIFY pgrst, 'reload schema';


-- ── THE HQ CATEGORY AND WHERE IT GOES ───────────────────────────
--
-- Through EXECUTE, because this database may not carry every earlier Nelos
-- migration and a plain statement naming a column that is not there fails at
-- PARSE time, before any guard can run. Dynamic SQL is parsed when it is
-- reached, so each part looks first.
DO $hq$
DECLARE
  cat_name   CONSTANT TEXT := 'From Culling Calculator - Request HQ Verification';
  has_cats   BOOLEAN := to_regclass('public.nelos_categories') IS NOT NULL;
  has_routes BOOLEAN := to_regclass('public.nelos_routes')     IS NOT NULL;
  has_mods   BOOLEAN := to_regclass('public.nelos_modules')    IS NOT NULL;
  has_modkey BOOLEAN := EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema='public' AND table_name='nelos_categories'
       AND column_name='module_key');
  has_scan   BOOLEAN := false;
  has_hq     BOOLEAN := false;
  n          INT;
BEGIN
  IF has_mods THEN
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_modules WHERE key='scan') $q$ INTO has_scan;
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_modules WHERE key='nursery_ops') $q$ INTO has_hq;
  END IF;

  IF NOT has_cats THEN
    RAISE NOTICE '1. SKIPPED -- no nelos_categories table.';
  ELSIF has_modkey THEN
    EXECUTE format($q$
      INSERT INTO public.nelos_categories (name, module_key, sort_order, default_priority, remark)
      SELECT %L, 'scan', 54, 'normal',
             'Raised from the Culling Calculator when a plot is still over the limit after a second pokok inang selection.'
       WHERE NOT EXISTS (SELECT 1 FROM public.nelos_categories
                          WHERE module_key='scan' AND lower(name)=lower(%L))
    $q$, cat_name, cat_name);
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE '1. Category under FC Portal: % row(s) added.', n;
  ELSE
    EXECUTE format($q$
      INSERT INTO public.nelos_categories (name, sort_order, default_priority, remark)
      SELECT %L, 54, 'normal',
             'Raised from the Culling Calculator when a plot is still over the limit after a second pokok inang selection.'
       WHERE NOT EXISTS (SELECT 1 FROM public.nelos_categories WHERE lower(name)=lower(%L))
    $q$, cat_name, cat_name);
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE '1. Category added (% row) with no section -- nelos_categories has no module_key column.', n;
  END IF;

  IF NOT has_routes THEN
    RAISE NOTICE '2. SKIPPED -- no nelos_routes table.';
  ELSIF NOT (has_scan AND has_hq) THEN
    RAISE NOTICE '2. SKIPPED -- nelos_modules is missing scan and/or nursery_ops.';
  ELSE
    EXECUTE format($q$
      INSERT INTO public.nelos_routes (source_module, category, to_module, updated_by)
      SELECT 'scan', %L, 'nursery_ops', 'system (RUN_ME_culling_inang)'
       WHERE NOT EXISTS (SELECT 1 FROM public.nelos_routes
                          WHERE source_module='scan' AND category=%L)
    $q$, cat_name, cat_name);
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE '2. FC Portal + HQ Verification -> HQ Operation: % row(s) added.', n;
  END IF;
END $hq$;


-- ── THE NELOS VERDICT, WORKED OUT BEFORE THE QUERY NAMES IT ─────
--
-- A plain SELECT naming nelos_routes is parsed whether or not the table is
-- there, and a CASE guarding it does not help: the parse fails first and
-- takes the whole file with it. This has cost a paste before. So the answer
-- is worked out here, into a session setting, and the query below names no
-- table that might not exist.
DO $verdict$
DECLARE ok BOOLEAN := false;
BEGIN
  IF to_regclass('public.nelos_routes') IS NOT NULL THEN
    EXECUTE $q$ SELECT EXISTS (SELECT 1 FROM public.nelos_routes
                                WHERE source_module='scan'
                                  AND category='From Culling Calculator - Request HQ Verification'
                                  AND to_module='nursery_ops') $q$ INTO ok;
  END IF;
  PERFORM set_config('mjm.cull_hq_route', CASE WHEN ok THEN 'OK' ELSE 'NOT OK' END, false);
END $verdict$;


-- ── WHAT A GOOD RESULT LOOKS LIKE ───────────────────────────────
--
-- Four rows. Every one of them should read OK.
--
--   1 table         the table, its unique index and row level security
--   2 grants        what the signed in portal may do with it
--   3 nelos         the category exists and routes to nursery_ops
--   4 stored        how many selections are held right now, over how many
--                   plots, and the highest round any of them has reached.
--                   Nought on a fresh install, and that is OK -- nothing has
--                   been counted yet.
--
-- Row 3 says NOT OK on a database with no Nelos tables, which is a real
-- answer rather than a fault in this file: the HQ button raises a case, and
-- without the route it lands back on the Field Conductor who pressed it.

SELECT 1 AS ord,
       'table' AS part,
       CASE WHEN to_regclass('public.fcportal_culling_inang') IS NOT NULL
             AND EXISTS (SELECT 1 FROM pg_indexes
                          WHERE schemaname='public'
                            AND indexname='fcportal_culling_inang_block')
             AND COALESCE((SELECT relrowsecurity FROM pg_class
                            WHERE oid = to_regclass('public.fcportal_culling_inang')), false)
            THEN 'OK' ELSE 'NOT OK' END AS verdict,
       'table, unique index on (plot, batch), row level security on' AS detail
UNION ALL
SELECT 2, 'grants',
       CASE WHEN (SELECT count(*) FROM information_schema.role_table_grants
                   WHERE table_schema='public' AND table_name='fcportal_culling_inang'
                     AND grantee='authenticated'
                     AND privilege_type IN ('SELECT','INSERT','UPDATE','DELETE')) = 4
            THEN 'OK' ELSE 'NOT OK' END,
       'select, insert, update and delete for a signed in portal'
UNION ALL
SELECT 3, 'nelos',
       current_setting('mjm.cull_hq_route', true),
       'HQ verification routes from the FC Portal to HQ Operation'
UNION ALL
SELECT 4, 'stored',
       'OK',
       COALESCE((SELECT count(*)::text FROM public.fcportal_culling_inang), '0')
       || ' selection row(s) over '
       || COALESCE((SELECT count(DISTINCT plot)::text FROM public.fcportal_culling_inang), '0')
       || ' plot(s), highest round '
       || COALESCE((SELECT max(attempt)::text FROM public.fcportal_culling_inang), '0')
 ORDER BY ord;
