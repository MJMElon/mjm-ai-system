-- ============================================================================
-- MJM AI POWERED SYSTEM -- RUN_ME_seal_hq_delivery.sql
--
-- SEAL MANAGE: HQ STOCK AND DELIVERIES TO SITE. One paste, safe to run twice.
-- Run it AFTER RUN_ME_seal_management.sql, which it builds on.
--
-- The seals now come to HQ first:
--
--   1. HQ orders from the supplier                  seal_orders (already there)
--   2. HQ receives them, keying the start and end    seal_hq_receipts
--   3. HQ sends a range to site                      seal_deliveries, Packed
--   4. HQ marks it delivered to the site office      status Delivered
--   5. Site keys the start and end AGAIN             a seal_receipts row with
--                                                    delivery_id, Received by
--
-- Step 5 is the receipt the site has always keyed (Mobile Receive Seals, or
-- the office Seal Manage page), with the delivery named on it. A trigger then
-- closes the delivery and compares the two ranges. A difference is never a
-- refused receipt -- what site counted is kept -- it is a seal_problems row
-- and a NELOS case to HQ, same as every other seal problem.
--
-- The last seal number anywhere in the system is what the next order to the
-- supplier starts after, and seal_hq_summary() hands it to the page.
-- ============================================================================


-- ── 1. HELPERS ───────────────────────────────────────────────────────────────

-- Every range in a JSON list, read the way the phones write it, smallest
-- number first and in the width it was scanned. A range that is not a number
-- is left out, which is the business of the trigger that reads it.
CREATE OR REPLACE FUNCTION public.seal_parse_ranges(p JSONB)
RETURNS TABLE (start_code TEXT, end_code TEXT, start_no BIGINT, end_no BIGINT)
LANGUAGE sql IMMUTABLE AS $$
  SELECT public.seal_code(LEAST(x.a, x.b), x.w), public.seal_code(GREATEST(x.a, x.b), x.w),
         LEAST(x.a, x.b), GREATEST(x.a, x.b)
    FROM (SELECT public.seal_no(el ->> 'start') AS a,
                 public.seal_no(COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start')) AS b,
                 GREATEST(length(public.seal_digits(el ->> 'start')),
                          length(public.seal_digits(COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start')))) AS w
            FROM jsonb_array_elements(CASE WHEN jsonb_typeof(p) = 'array' THEN p ELSE '[]'::jsonb END) el) x
   WHERE x.a IS NOT NULL AND x.b IS NOT NULL
$$;

-- How many seals are in A, how many in B, and how many in both.
CREATE OR REPLACE FUNCTION public.seal_range_qty(p JSONB)
RETURNS BIGINT LANGUAGE sql IMMUTABLE AS $$
  SELECT COALESCE(sum(r.end_no - r.start_no + 1), 0)::BIGINT FROM public.seal_parse_ranges(p) r
$$;

CREATE OR REPLACE FUNCTION public.seal_overlap_qty(p_a JSONB, p_b JSONB)
RETURNS BIGINT LANGUAGE sql IMMUTABLE AS $$
  SELECT COALESCE(sum(GREATEST(0, LEAST(a.end_no, b.end_no) - GREATEST(a.start_no, b.start_no) + 1)), 0)::BIGINT
    FROM public.seal_parse_ranges(p_a) a, public.seal_parse_ranges(p_b) b
$$;

-- The seals in A that are not in B, as a list of ranges.
CREATE OR REPLACE FUNCTION public.seal_minus(p_a JSONB, p_b JSONB)
RETURNS JSONB LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  a    RECORD;
  b    RECORD;
  cur  BIGINT;
  w    INT;
  out  JSONB := '[]'::jsonb;
BEGIN
  FOR a IN SELECT * FROM public.seal_parse_ranges(p_a) ORDER BY 3 LOOP
    w := length(a.start_code);
    cur := a.start_no;
    FOR b IN SELECT * FROM public.seal_parse_ranges(p_b) r
              WHERE r.start_no <= a.end_no AND r.end_no >= a.start_no ORDER BY 3 LOOP
      IF b.start_no > cur THEN
        out := out || jsonb_build_array(jsonb_build_object('start', public.seal_code(cur, w), 'end', public.seal_code(b.start_no - 1, w)));
      END IF;
      cur := GREATEST(cur, b.end_no + 1);
    END LOOP;
    IF cur <= a.end_no THEN
      out := out || jsonb_build_array(jsonb_build_object('start', public.seal_code(cur, w), 'end', public.seal_code(a.end_no, w)));
    END IF;
  END LOOP;
  RETURN out;
END $$;

-- A list of ranges as people read it: 0009001 - 0009600, 0012345
CREATE OR REPLACE FUNCTION public.seal_ranges_text(p JSONB)
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
  SELECT COALESCE(string_agg(CASE WHEN r.start_no = r.end_no THEN r.start_code
                                  ELSE r.start_code || ' - ' || r.end_code END, ', ' ORDER BY r.start_no), 'none')
    FROM public.seal_parse_ranges(p) r
$$;


-- ── 2. TABLES ────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.seal_hq_receipts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_ref     TEXT UNIQUE,
  order_id       BIGINT REFERENCES public.seal_orders(id) ON DELETE SET NULL,
  received_date  DATE NOT NULL DEFAULT CURRENT_DATE,
  ranges         JSONB NOT NULL DEFAULT '[]'::jsonb,
  photo_urls     JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_opening     BOOLEAN NOT NULL DEFAULT false,
  remark         TEXT,
  received_by    TEXT,
  received_by_id UUID,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.seal_hq_ranges (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_id  BIGINT NOT NULL REFERENCES public.seal_hq_receipts(id) ON DELETE CASCADE,
  start_code  TEXT NOT NULL,
  end_code    TEXT NOT NULL,
  start_no    BIGINT NOT NULL,
  end_no      BIGINT NOT NULL,
  qty         BIGINT GENERATED ALWAYS AS (end_no - start_no + 1) STORED,
  CHECK (end_no >= start_no)
);
CREATE INDEX IF NOT EXISTS seal_hq_ranges_no_idx ON public.seal_hq_ranges (start_no, end_no);

-- One delivery from HQ to site. Its status moves like a parcel:
-- packed (HQ made it) then delivered (HQ handed it to the site office)
-- then received (site keyed the numbers again).
CREATE TABLE IF NOT EXISTS public.seal_deliveries (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_ref      TEXT UNIQUE,
  site            TEXT NOT NULL DEFAULT 'UNN 1',
  ranges          JSONB NOT NULL DEFAULT '[]'::jsonb,
  remark          TEXT,
  status          TEXT NOT NULL DEFAULT 'packed' CHECK (status IN ('packed', 'delivered', 'received')),
  packed_by       TEXT,
  packed_by_id    UUID,
  packed_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivered_by    TEXT,
  delivered_at    TIMESTAMPTZ,
  received_by     TEXT,
  received_at     TIMESTAMPTZ,
  receipt_id      BIGINT,
  received_ranges JSONB,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.seal_delivery_ranges (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id BIGINT NOT NULL REFERENCES public.seal_deliveries(id) ON DELETE CASCADE,
  start_code  TEXT NOT NULL,
  end_code    TEXT NOT NULL,
  start_no    BIGINT NOT NULL,
  end_no      BIGINT NOT NULL,
  qty         BIGINT GENERATED ALWAYS AS (end_no - start_no + 1) STORED,
  CHECK (end_no >= start_no)
);
CREATE INDEX IF NOT EXISTS seal_delivery_ranges_no_idx ON public.seal_delivery_ranges (start_no, end_no);

-- The site receipt names the delivery it confirms. Empty for opening stock
-- and for anything received before deliveries existed.
ALTER TABLE public.seal_receipts ADD COLUMN IF NOT EXISTS delivery_id BIGINT REFERENCES public.seal_deliveries(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS seal_receipts_delivery_idx ON public.seal_receipts (delivery_id);

ALTER TABLE public.seal_problems ADD COLUMN IF NOT EXISTS delivery_id BIGINT;


-- ── 3. NELOS ─────────────────────────────────────────────────────────────────
-- The same function as RUN_ME_seal_management.sql, word for word, now with
-- titles for the four delivery problems and one open case per delivery.
-- tests/seal_dashboard.cjs holds the two copies to each other.

CREATE OR REPLACE FUNCTION public.seal_raise_case(p_id BIGINT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  pr        public.seal_problems%ROWTYPE;
  v_case    BIGINT;
  v_module  TEXT;
  v_title   TEXT;
  v_body    TEXT;
BEGIN
  IF to_regclass('public.nelos_cases') IS NULL THEN RETURN NULL; END IF;
  SELECT * INTO pr FROM public.seal_problems WHERE id = p_id;
  IF NOT FOUND THEN RETURN NULL; END IF;

  v_body := pr.detail;

  SELECT c.id INTO v_case
    FROM public.seal_problems q
    JOIN public.nelos_cases c ON c.id = q.nelos_case_id
   WHERE q.id <> pr.id
     AND q.kind = pr.kind
     AND q.al_number IS NOT DISTINCT FROM pr.al_number
     AND q.receipt_id IS NOT DISTINCT FROM pr.receipt_id
     AND q.delivery_id IS NOT DISTINCT FROM pr.delivery_id
     AND c.status IN ('open', 'in_progress')
   ORDER BY c.id DESC
   LIMIT 1;

  IF v_case IS NOT NULL THEN
    INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
    VALUES (v_case, v_body, 'comment', 'Seal check (system)');
    UPDATE public.seal_problems SET nelos_case_id = v_case WHERE id = pr.id;
    RETURN v_case;
  END IF;

  SELECT NULLIF(s.nelos_module, '') INTO v_module FROM public.seal_settings s WHERE s.id = 1;
  IF v_module IS NULL AND to_regclass('public.nelos_modules') IS NOT NULL THEN
    SELECT m.key INTO v_module
      FROM public.nelos_modules m
     WHERE COALESCE((to_jsonb(m) ->> 'sees_all_cases')::BOOLEAN, false)
     ORDER BY m.sort_order
     LIMIT 1;
  END IF;
  v_module := COALESCE(v_module, 'nursery_ops');

  v_title := CASE pr.kind
    WHEN 'consent_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' given twice, already with ' || COALESCE(pr.other_customer, '?') || ' (' || COALESCE(pr.other_al, '?') || ')'
    WHEN 'consent_not_received' THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' were never received'
    WHEN 'consent_bad_range'    THEN 'Seal range could not be read on a consent'
    WHEN 'receive_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' received twice'
    WHEN 'collect_other'        THEN 'Seal ' || pr.seal_from || ' of ' || COALESCE(pr.other_customer, '?') || ' (' || COALESCE(pr.other_al, '?') || ') collected for another customer'
    WHEN 'collect_not_issued'   THEN 'Seal ' || pr.seal_from || ' collected but on no consent'
    WHEN 'hq_receive_overlap'   THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' received at HQ twice'
    WHEN 'deliver_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' sent to site twice'
    WHEN 'delivery_mismatch'    THEN 'Delivery #' || COALESCE(pr.delivery_id::TEXT, '?') || ' received at site does not match what HQ sent'
    WHEN 'delivery_twice'       THEN 'Delivery #' || COALESCE(pr.delivery_id::TEXT, '?') || ' confirmed received twice'
    ELSE 'Seal problem' END;
  IF pr.al_number IS NOT NULL THEN
    v_title := v_title || ', for ' || COALESCE(pr.customer_name, '?') || ' (' || pr.al_number || ')';
  END IF;

  INSERT INTO public.nelos_cases
    (title, description, category, priority, status, source_module, assigned_module,
     source_ref, nursery_name, raised_by)
  VALUES
    (left(v_title, 300),
     v_body || ' Pending action: check the seals and correct the record.',
     'Seal', 'high', 'open', 'seal', v_module,
     '../seal/seal_dashboard.html?tab=problems&problem=' || pr.id,
     (SELECT site FROM public.seal_settings WHERE id = 1),
     'Seal check (system)')
  RETURNING id INTO v_case;

  INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
  VALUES (v_case, v_body, 'comment', 'Seal check (system)');

  UPDATE public.seal_problems SET nelos_case_id = v_case WHERE id = pr.id;
  RETURN v_case;
EXCEPTION WHEN OTHERS THEN
  -- A NELOS that will not take the case must never refuse the consent, the
  -- receipt or the scan. The problem row is kept and says so.
  UPDATE public.seal_problems
     SET detail = detail || ' [NELOS case not opened: ' || SQLERRM || ']'
   WHERE id = p_id;
  RETURN NULL;
END $$;

-- The same as seal_add_problem, naming the delivery the problem is about, so
-- the case it opens is that delivery and nothing else.
CREATE OR REPLACE FUNCTION public.seal_add_delivery_problem(
  p_kind TEXT, p_delivery BIGINT, p_receipt BIGINT, p_from TEXT, p_to TEXT, p_qty BIGINT, p_detail TEXT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id BIGINT;
BEGIN
  INSERT INTO public.seal_problems (kind, delivery_id, receipt_id, seal_from, seal_to, qty, detail)
  VALUES (p_kind, p_delivery, p_receipt, p_from, p_to, p_qty, p_detail)
  RETURNING id INTO v_id;
  PERFORM public.seal_raise_case(v_id);
  RETURN v_id;
END $$;

DO $mod$
BEGIN
  IF to_regclass('public.nelos_modules') IS NOT NULL THEN
    UPDATE public.nelos_modules SET label = 'Seal Manage' WHERE key = 'seal' AND label = 'Seal Management';
  END IF;
  -- Automate Cases lists what the system opens by itself, so the Seal title
  -- names the delivery checks too. Through EXECUTE because an older
  -- nelos_categories may have no auto_condition column.
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'nelos_categories'
                AND column_name = 'auto_condition') THEN
    EXECUTE $q$
      UPDATE public.nelos_categories
         SET auto_condition =
             'A seal check finds a problem: a range given twice, a range never received, '
             'a range that could not be read, a range received twice, a seal collected '
             'for another customer, a seal collected on no consent, a range received at HQ '
             'twice, a range sent to site twice, or a delivery that site received '
             'differently from what HQ sent'
       WHERE lower(name) = 'seal'
    $q$;
  END IF;
END $mod$;


-- ── 4. TRIGGERS ──────────────────────────────────────────────────────────────

-- HQ receives from the supplier: one row per range, and a range HQ already
-- has is a problem.
CREATE OR REPLACE FUNCTION public.seal_sync_hq_receipt()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r    RECORD;
  hit  RECORD;
  w    INT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.ranges IS NOT DISTINCT FROM OLD.ranges THEN RETURN NEW; END IF;
  DELETE FROM public.seal_hq_ranges WHERE receipt_id = NEW.id;
  FOR r IN SELECT * FROM public.seal_parse_ranges(NEW.ranges) LOOP
    w := length(r.start_code);
    FOR hit IN
      SELECT h.receipt_id, GREATEST(h.start_no, r.start_no) AS o1, LEAST(h.end_no, r.end_no) AS o2
        FROM public.seal_hq_ranges h
       WHERE h.receipt_id <> NEW.id AND h.start_no <= r.end_no AND h.end_no >= r.start_no
    LOOP
      PERFORM public.seal_add_delivery_problem('hq_receive_overlap', NULL, NULL,
        public.seal_code(hit.o1, w), public.seal_code(hit.o2, w), hit.o2 - hit.o1 + 1,
        'Seals ' || public.seal_code(hit.o1, w) || ' - ' || public.seal_code(hit.o2, w)
          || ' on HQ receipt ' || NEW.id || ' were already received at HQ on receipt ' || hit.receipt_id || '.');
    END LOOP;
    INSERT INTO public.seal_hq_ranges (receipt_id, start_code, end_code, start_no, end_no)
    VALUES (NEW.id, r.start_code, r.end_code, r.start_no, r.end_no);
  END LOOP;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS seal_sync_hq_receipt ON public.seal_hq_receipts;
CREATE TRIGGER seal_sync_hq_receipt
  AFTER INSERT OR UPDATE OF ranges ON public.seal_hq_receipts
  FOR EACH ROW EXECUTE FUNCTION public.seal_sync_hq_receipt();

-- HQ sends to site: one row per range, and a range already sent on another
-- delivery is a problem.
CREATE OR REPLACE FUNCTION public.seal_sync_delivery()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r    RECORD;
  hit  RECORD;
  w    INT;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.ranges IS NOT DISTINCT FROM OLD.ranges THEN RETURN NEW; END IF;
  DELETE FROM public.seal_delivery_ranges WHERE delivery_id = NEW.id;
  FOR r IN SELECT * FROM public.seal_parse_ranges(NEW.ranges) LOOP
    w := length(r.start_code);
    FOR hit IN
      SELECT d.delivery_id, GREATEST(d.start_no, r.start_no) AS o1, LEAST(d.end_no, r.end_no) AS o2
        FROM public.seal_delivery_ranges d
       WHERE d.delivery_id <> NEW.id AND d.start_no <= r.end_no AND d.end_no >= r.start_no
    LOOP
      PERFORM public.seal_add_delivery_problem('deliver_overlap', NEW.id, NULL,
        public.seal_code(hit.o1, w), public.seal_code(hit.o2, w), hit.o2 - hit.o1 + 1,
        'Seals ' || public.seal_code(hit.o1, w) || ' - ' || public.seal_code(hit.o2, w)
          || ' on delivery #' || NEW.id || ' were already sent to site on delivery #' || hit.delivery_id || '.');
    END LOOP;
    INSERT INTO public.seal_delivery_ranges (delivery_id, start_code, end_code, start_no, end_no)
    VALUES (NEW.id, r.start_code, r.end_code, r.start_no, r.end_no);
  END LOOP;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS seal_sync_delivery ON public.seal_deliveries;
CREATE TRIGGER seal_sync_delivery
  AFTER INSERT OR UPDATE OF ranges ON public.seal_deliveries
  FOR EACH ROW EXECUTE FUNCTION public.seal_sync_delivery();

-- Site keys the delivery again. The receipt closes the delivery, and what
-- site counted is compared with what HQ sent, both ways round.
CREATE OR REPLACE FUNCTION public.seal_confirm_delivery()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  d        public.seal_deliveries%ROWTYPE;
  v_sent   BIGINT;
  v_got    BIGINT;
  v_both   BIGINT;
  v_miss   JSONB;
  v_extra  JSONB;
BEGIN
  IF NEW.delivery_id IS NULL THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' AND NEW.delivery_id IS NOT DISTINCT FROM OLD.delivery_id
     AND NEW.ranges IS NOT DISTINCT FROM OLD.ranges THEN RETURN NEW; END IF;
  SELECT * INTO d FROM public.seal_deliveries WHERE id = NEW.delivery_id;
  IF NOT FOUND THEN RETURN NEW; END IF;

  -- Offline, two phones can each confirm the same delivery. The first one
  -- closed it, the second is kept as the receipt it is and named.
  IF d.status = 'received' AND d.receipt_id IS DISTINCT FROM NEW.id THEN
    PERFORM public.seal_add_delivery_problem('delivery_twice', d.id, NEW.id, NULL, NULL, NULL,
      'Delivery #' || d.id || ' was already confirmed received by ' || COALESCE(d.received_by, '?')
        || ' (site receipt ' || COALESCE(d.receipt_id::TEXT, '?') || '). Site receipt ' || NEW.id
        || ' by ' || COALESCE(NEW.received_by, '?') || ' confirms it again: '
        || public.seal_ranges_text(NEW.ranges) || '.');
    RETURN NEW;
  END IF;

  UPDATE public.seal_deliveries
     SET status          = 'received',
         received_by     = NEW.received_by,
         received_at     = COALESCE(NEW.created_at, now()),
         receipt_id      = NEW.id,
         received_ranges = NEW.ranges
   WHERE id = d.id;

  v_sent  := public.seal_range_qty(d.ranges);
  v_got   := public.seal_range_qty(NEW.ranges);
  v_both  := public.seal_overlap_qty(d.ranges, NEW.ranges);
  IF v_sent = v_both AND v_got = v_both THEN RETURN NEW; END IF;

  v_miss  := public.seal_minus(d.ranges, NEW.ranges);
  v_extra := public.seal_minus(NEW.ranges, d.ranges);
  PERFORM public.seal_add_delivery_problem('delivery_mismatch', d.id, NEW.id,
    (SELECT min(start_code) FROM public.seal_parse_ranges(d.ranges)),
    (SELECT max(end_code) FROM public.seal_parse_ranges(d.ranges)),
    (v_sent - v_both) + (v_got - v_both),
    'Delivery #' || d.id || ': HQ sent ' || public.seal_ranges_text(d.ranges) || ' (' || v_sent || ' seals). '
      || COALESCE(NEW.site, 'Site') || ' received ' || public.seal_ranges_text(NEW.ranges) || ' (' || v_got || ' seals), keyed by '
      || COALESCE(NEW.received_by, '?') || '. '
      || (v_sent - v_both) || ' sent but not received: ' || public.seal_ranges_text(v_miss) || '. '
      || (v_got - v_both) || ' received but not on the delivery: ' || public.seal_ranges_text(v_extra) || '.');
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS seal_confirm_delivery ON public.seal_receipts;
CREATE TRIGGER seal_confirm_delivery
  AFTER INSERT OR UPDATE OF delivery_id, ranges ON public.seal_receipts
  FOR EACH ROW EXECUTE FUNCTION public.seal_confirm_delivery();

-- A site receipt deleted takes its confirmation with it, so the delivery goes
-- back to waiting rather than reading received over nothing.
CREATE OR REPLACE FUNCTION public.seal_unconfirm_delivery()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  UPDATE public.seal_deliveries
     SET status          = CASE WHEN delivered_at IS NOT NULL THEN 'delivered' ELSE 'packed' END,
         received_by     = NULL,
         received_at     = NULL,
         receipt_id      = NULL,
         received_ranges = NULL
   WHERE receipt_id = OLD.id;
  RETURN OLD;
END $$;

DROP TRIGGER IF EXISTS seal_unconfirm_delivery ON public.seal_receipts;
CREATE TRIGGER seal_unconfirm_delivery
  AFTER DELETE ON public.seal_receipts
  FOR EACH ROW EXECUTE FUNCTION public.seal_unconfirm_delivery();


-- ── 5. WHAT THE PAGE ASKS ────────────────────────────────────────────────────

-- The seals at HQ: received from the supplier and not yet on a delivery.
DROP FUNCTION IF EXISTS public.seal_hq_stock();
CREATE FUNCTION public.seal_hq_stock()
RETURNS TABLE (start_code TEXT, end_code TEXT, start_no BIGINT, end_no BIGINT, qty BIGINT,
               received_date DATE, receipt_id BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r    RECORD;
  d    RECORD;
  cur  BIGINT;
  w    INT;
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  FOR r IN SELECT h.*, s.received_date AS rdate FROM public.seal_hq_ranges h
             JOIN public.seal_hq_receipts s ON s.id = h.receipt_id
            ORDER BY h.start_no LOOP
    w := length(r.start_code);
    cur := r.start_no;
    FOR d IN SELECT x.start_no AS s, x.end_no AS e FROM public.seal_delivery_ranges x
              WHERE x.start_no <= r.end_no AND x.end_no >= r.start_no
              ORDER BY x.start_no LOOP
      IF d.s > cur THEN
        RETURN QUERY SELECT public.seal_code(cur, w), public.seal_code(LEAST(d.s - 1, r.end_no), w),
          cur, LEAST(d.s - 1, r.end_no), (LEAST(d.s - 1, r.end_no) - cur + 1)::BIGINT, r.rdate::DATE, r.receipt_id;
      END IF;
      cur := GREATEST(cur, d.e + 1);
    END LOOP;
    IF cur <= r.end_no THEN
      RETURN QUERY SELECT public.seal_code(cur, w), public.seal_code(r.end_no, w),
        cur, r.end_no, (r.end_no - cur + 1)::BIGINT, r.rdate::DATE, r.receipt_id;
    END IF;
  END LOOP;
END $$;

-- The four figures at the top of the HQ page, and the last seal number the
-- system has ever seen, received, sent or given out, so the next order to the
-- supplier can start after it.
DROP FUNCTION IF EXISTS public.seal_hq_summary();
CREATE FUNCTION public.seal_hq_summary()
RETURNS TABLE (last_code TEXT, next_code TEXT, hq_received BIGINT, hq_stock BIGINT,
               on_the_way BIGINT, site_stock BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_last  BIGINT;
  v_code  TEXT;
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  SELECT x.n, x.c INTO v_last, v_code FROM (
    SELECT end_no AS n, end_code AS c FROM public.seal_hq_ranges
    UNION ALL SELECT end_no, end_code FROM public.seal_receipt_ranges
    UNION ALL SELECT end_no, end_code FROM public.seal_delivery_ranges
    UNION ALL SELECT end_no, end_code FROM public.seal_allocations
  ) x ORDER BY x.n DESC LIMIT 1;
  RETURN QUERY SELECT
    v_code,
    CASE WHEN v_last IS NULL THEN NULL ELSE public.seal_code(v_last + 1, length(v_code)) END,
    (SELECT COALESCE(sum(qty), 0) FROM public.seal_hq_ranges)::BIGINT,
    (SELECT COALESCE(sum(s.qty), 0) FROM public.seal_hq_stock() s)::BIGINT,
    (SELECT COALESCE(sum(r.qty), 0) FROM public.seal_delivery_ranges r
       JOIN public.seal_deliveries d ON d.id = r.delivery_id WHERE d.status <> 'received')::BIGINT,
    (SELECT COALESCE(sum(g.qty), 0) FROM public.seal_segments(NULL) g WHERE g.seg_status = 'in_stock')::BIGINT;
END $$;

-- A range checked before it is saved, on the HQ page.
--   hq_receive  already received at HQ               block
--   deliver     already sent on another delivery     block
--               not received at HQ                   warn
--   confirm     what the delivery sent, to compare   (the page compares)
DROP FUNCTION IF EXISTS public.seal_check_hq(TEXT, TEXT, TEXT);
CREATE FUNCTION public.seal_check_hq(p_start TEXT, p_end TEXT, p_kind TEXT)
RETURNS TABLE (problem TEXT, from_code TEXT, to_code TEXT, qty BIGINT, detail TEXT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE n1 BIGINT; n2 BIGINT; t BIGINT; w INT; v_cov BIGINT;
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  n1 := public.seal_no(p_start);
  n2 := public.seal_no(COALESCE(NULLIF(p_end, ''), p_start));
  IF n1 IS NULL OR n2 IS NULL THEN
    RETURN QUERY SELECT 'bad'::TEXT, p_start, p_end, 0::BIGINT, 'Not a seal number'::TEXT;
    RETURN;
  END IF;
  IF n2 < n1 THEN t := n1; n1 := n2; n2 := t; END IF;
  w := GREATEST(length(public.seal_digits(p_start)), length(public.seal_digits(COALESCE(NULLIF(p_end, ''), p_start))));

  IF p_kind = 'hq_receive' THEN
    RETURN QUERY
      SELECT 'received'::TEXT,
             public.seal_code(GREATEST(h.start_no, n1), w), public.seal_code(LEAST(h.end_no, n2), w),
             (LEAST(h.end_no, n2) - GREATEST(h.start_no, n1) + 1)::BIGINT,
             ('Already received at HQ on ' || to_char(s.received_date, 'DD Mon YYYY'))::TEXT
        FROM public.seal_hq_ranges h JOIN public.seal_hq_receipts s ON s.id = h.receipt_id
       WHERE h.start_no <= n2 AND h.end_no >= n1
       ORDER BY h.start_no;
    RETURN;
  END IF;

  IF p_kind = 'deliver' THEN
    RETURN QUERY
      SELECT 'delivered'::TEXT,
             public.seal_code(GREATEST(x.start_no, n1), w), public.seal_code(LEAST(x.end_no, n2), w),
             (LEAST(x.end_no, n2) - GREATEST(x.start_no, n1) + 1)::BIGINT,
             ('Already sent to ' || d.site || ' on delivery #' || d.id || ', ' || to_char(d.packed_at, 'DD Mon YYYY'))::TEXT
        FROM public.seal_delivery_ranges x JOIN public.seal_deliveries d ON d.id = x.delivery_id
       WHERE x.start_no <= n2 AND x.end_no >= n1
       ORDER BY x.start_no;
    SELECT COALESCE(sum(LEAST(h.end_no, n2) - GREATEST(h.start_no, n1) + 1), 0) INTO v_cov
      FROM public.seal_hq_ranges h
     WHERE h.start_no <= n2 AND h.end_no >= n1;
    IF v_cov < n2 - n1 + 1 THEN
      RETURN QUERY SELECT 'not_at_hq'::TEXT, public.seal_code(n1, w), public.seal_code(n2, w),
        ((n2 - n1 + 1) - v_cov)::BIGINT,
        (((n2 - n1 + 1) - v_cov) || ' of these seals were never received at HQ')::TEXT;
    END IF;
  END IF;
END $$;


