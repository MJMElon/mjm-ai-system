-- ── 8. READING IT ────────────────────────────────────────────────────────────

-- Asked by a phone WITH signal before it saves. problem is one of
--   allocated     part of the range already belongs to a customer (blocks)
--   not_received  part of it was never received at UNN 1 (warns)
--   received      part of a range being received was received before (blocks)
CREATE OR REPLACE FUNCTION public.seal_check_range(p_start TEXT, p_end TEXT, p_kind TEXT DEFAULT 'consent')
RETURNS TABLE (problem TEXT, al_number TEXT, customer_name TEXT, from_code TEXT, to_code TEXT, qty BIGINT, detail TEXT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE n1 BIGINT; n2 BIGINT; t BIGINT; w INT; v_cov BIGINT;
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  n1 := public.seal_no(p_start);
  n2 := public.seal_no(COALESCE(NULLIF(p_end, ''), p_start));
  IF n1 IS NULL OR n2 IS NULL THEN
    RETURN QUERY SELECT 'bad'::TEXT, NULL::TEXT, NULL::TEXT, p_start, p_end, 0::BIGINT, 'Not a seal number'::TEXT;
    RETURN;
  END IF;
  IF n2 < n1 THEN t := n1; n1 := n2; n2 := t; END IF;
  w := GREATEST(length(public.seal_digits(p_start)), length(public.seal_digits(COALESCE(NULLIF(p_end, ''), p_start))));

  IF p_kind = 'receive' THEN
    RETURN QUERY
      SELECT 'received'::TEXT, NULL::TEXT, NULL::TEXT,
             public.seal_code(GREATEST(r.start_no, n1), w), public.seal_code(LEAST(r.end_no, n2), w),
             (LEAST(r.end_no, n2) - GREATEST(r.start_no, n1) + 1)::BIGINT,
             ('Already received on ' || to_char(s.received_date, 'DD Mon YYYY'))::TEXT
        FROM public.seal_receipt_ranges r JOIN public.seal_receipts s ON s.id = r.receipt_id
       WHERE r.start_no <= n2 AND r.end_no >= n1
       ORDER BY r.start_no;
    RETURN;
  END IF;

  RETURN QUERY
    SELECT 'allocated'::TEXT, a.al_number, a.customer_name,
           public.seal_code(GREATEST(a.start_no, n1), w), public.seal_code(LEAST(a.end_no, n2), w),
           (LEAST(a.end_no, n2) - GREATEST(a.start_no, n1) + 1)::BIGINT,
           ('Consent of ' || to_char(COALESCE(a.consent_at, a.created_at), 'DD Mon YYYY'))::TEXT
      FROM public.seal_allocations a
     WHERE a.start_no <= n2 AND a.end_no >= n1
     ORDER BY a.start_no;

  SELECT COALESCE(sum(LEAST(r.end_no, n2) - GREATEST(r.start_no, n1) + 1), 0) INTO v_cov
    FROM public.seal_receipt_ranges r
   WHERE r.start_no <= n2 AND r.end_no >= n1;
  IF v_cov < n2 - n1 + 1 THEN
    RETURN QUERY SELECT 'not_received'::TEXT, NULL::TEXT, NULL::TEXT,
      public.seal_code(n1, w), public.seal_code(n2, w), ((n2 - n1 + 1) - v_cov)::BIGINT,
      (((n2 - n1 + 1) - v_cov) || ' of these seals were never received at UNN 1')::TEXT;
  END IF;
END $$;

-- Every range in the system, split by what has happened to each part of it.
-- seg_status: in_stock | pending | scanned | collected
DROP FUNCTION IF EXISTS public.seal_segments(TEXT);
CREATE FUNCTION public.seal_segments(p_al TEXT DEFAULT NULL)
RETURNS TABLE (seg_status TEXT, start_code TEXT, end_code TEXT, start_no BIGINT, end_no BIGINT, qty BIGINT,
               al_number TEXT, customer_name TEXT, consent_id TEXT, consent_at TIMESTAMPTZ,
               do_number TEXT, allocation_id BIGINT, receipt_id BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  a    RECORD;
  isl  RECORD;
  r    RECORD;
  cur  BIGINT;
  w    INT;
BEGIN
  FOR a IN SELECT * FROM public.seal_allocations x
            WHERE p_al IS NULL OR x.al_number = p_al
            ORDER BY x.start_no LOOP
    w := length(a.start_code);
    cur := a.start_no;
    FOR isl IN
      SELECT g.do_number AS dn, min(g.seal_no) AS s, max(g.seal_no) AS e, count(*) AS n
        FROM (SELECT DISTINCT ON (f.seal_no) f.seal_no, f.do_number,
                     f.seal_no - dense_rank() OVER (PARTITION BY COALESCE(f.do_number, '') ORDER BY f.seal_no) AS grp
                FROM (SELECT x.seal_no, x.do_number FROM public.fcportal_scan_records x
                       WHERE x.al_number = a.al_number
                         AND x.seal_no BETWEEN a.start_no AND a.end_no
                      UNION ALL
                      -- a seal the office settled as delivered reads as scanned on its DO
                      SELECT gs.n, z.do_number
                        FROM public.seal_settled_scans z,
                             generate_series(GREATEST(z.start_no, a.start_no), LEAST(z.end_no, a.end_no)) AS gs(n)
                       WHERE z.al_number = a.al_number AND z.outcome = 'delivered'
                         AND z.start_no <= a.end_no AND z.end_no >= a.start_no) f
               ORDER BY f.seal_no, f.do_number NULLS LAST) g
       GROUP BY g.do_number, g.grp
       ORDER BY min(g.seal_no)
    LOOP
      IF isl.s > cur THEN
        RETURN QUERY SELECT 'pending'::TEXT, public.seal_code(cur, w), public.seal_code(isl.s - 1, w), cur, isl.s - 1,
          isl.s - cur, a.al_number, a.customer_name, a.consent_id, a.consent_at, NULL::TEXT, a.id, NULL::BIGINT;
      END IF;
      RETURN QUERY SELECT CASE WHEN isl.dn IS NULL THEN 'scanned' ELSE 'collected' END,
        public.seal_code(isl.s, w), public.seal_code(isl.e, w), isl.s, isl.e, isl.n,
        a.al_number, a.customer_name, a.consent_id, a.consent_at, isl.dn, a.id, NULL::BIGINT;
      cur := GREATEST(cur, isl.e + 1);
    END LOOP;
    IF cur <= a.end_no THEN
      RETURN QUERY SELECT 'pending'::TEXT, public.seal_code(cur, w), public.seal_code(a.end_no, w), cur, a.end_no,
        a.end_no - cur + 1, a.al_number, a.customer_name, a.consent_id, a.consent_at, NULL::TEXT, a.id, NULL::BIGINT;
    END IF;
  END LOOP;

  IF p_al IS NOT NULL THEN RETURN; END IF;

  -- What was received and is on no consent is in stock.
  FOR r IN SELECT x.*, s.received_date FROM public.seal_receipt_ranges x
             JOIN public.seal_receipts s ON s.id = x.receipt_id
            ORDER BY x.start_no LOOP
    w := length(r.start_code);
    cur := r.start_no;
    FOR a IN SELECT x.start_no AS s, x.end_no AS e FROM public.seal_allocations x
              WHERE x.start_no <= r.end_no AND x.end_no >= r.start_no
              ORDER BY x.start_no LOOP
      IF a.s > cur THEN
        RETURN QUERY SELECT 'in_stock'::TEXT, public.seal_code(cur, w), public.seal_code(LEAST(a.s - 1, r.end_no), w),
          cur, LEAST(a.s - 1, r.end_no), LEAST(a.s - 1, r.end_no) - cur + 1,
          NULL::TEXT, NULL::TEXT, NULL::TEXT, r.received_date::TIMESTAMPTZ, NULL::TEXT, NULL::BIGINT, r.receipt_id;
      END IF;
      cur := GREATEST(cur, a.e + 1);
    END LOOP;
    IF cur <= r.end_no THEN
      RETURN QUERY SELECT 'in_stock'::TEXT, public.seal_code(cur, w), public.seal_code(r.end_no, w),
        cur, r.end_no, r.end_no - cur + 1,
        NULL::TEXT, NULL::TEXT, NULL::TEXT, r.received_date::TIMESTAMPTZ, NULL::TEXT, NULL::BIGINT, r.receipt_id;
    END IF;
  END LOOP;
END $$;

-- The Seal list for staff, with a search. A search that is all digits finds
-- the part holding that seal number. Anything else matches customer or AL.
DROP FUNCTION IF EXISTS public.seal_list(TEXT, TEXT);
CREATE FUNCTION public.seal_list(p_search TEXT DEFAULT NULL, p_status TEXT DEFAULT NULL)
RETURNS TABLE (seg_status TEXT, start_code TEXT, end_code TEXT, start_no BIGINT, end_no BIGINT, qty BIGINT,
               al_number TEXT, customer_name TEXT, consent_id TEXT, consent_at TIMESTAMPTZ,
               do_number TEXT, allocation_id BIGINT, receipt_id BIGINT, open_problems BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_q TEXT := NULLIF(trim(COALESCE(p_search, '')), ''); v_n BIGINT;
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  IF v_q IS NOT NULL AND public.seal_digits(v_q) = v_q THEN v_n := public.seal_no(v_q); END IF;
  RETURN QUERY
    SELECT g.*,
           (SELECT count(*) FROM public.seal_problems p
             WHERE p.status = 'open' AND p.al_number = g.al_number)::BIGINT
      FROM public.seal_segments(NULL) g
     WHERE (p_status IS NULL OR g.seg_status = p_status)
       AND (v_q IS NULL
            OR (v_n IS NOT NULL AND v_n BETWEEN g.start_no AND g.end_no)
            OR (v_n IS NULL AND (g.customer_name ILIKE '%' || v_q || '%'
                              OR g.al_number ILIKE '%' || v_q || '%'
                              OR g.do_number ILIKE '%' || v_q || '%')))
     ORDER BY g.start_no;
END $$;

-- Is this login allowed to see this order? Staff, or the customer who owns it
-- on the Sales Web. The AL of a Sales Web order is its order number.
CREATE OR REPLACE FUNCTION public.seal_order_als(p_order TEXT)
RETURNS TEXT[] LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_ok BOOLEAN := public.seal_is_staff(); v_als TEXT[];
BEGIN
  IF NOT v_ok AND to_regclass('public.salesweb_customer_orders') IS NOT NULL THEN
    EXECUTE 'SELECT EXISTS (SELECT 1 FROM public.salesweb_customer_orders o
                             WHERE o.order_number = $1 AND o.customer_id = auth.uid())'
       INTO v_ok USING p_order;
  END IF;
  IF NOT v_ok THEN RETURN ARRAY[]::TEXT[]; END IF;
  SELECT array_agg(DISTINCT x) INTO v_als FROM (
    SELECT p_order AS x
    UNION SELECT al.al_number FROM public.shared_al_orders al WHERE al.order_number = p_order
  ) q WHERE x IS NOT NULL;
  RETURN COALESCE(v_als, ARRAY[]::TEXT[]);
END $$;

-- Seals of one order: every part of every range, for the order screen and the
-- customer portal. Stock is never in it.
DROP FUNCTION IF EXISTS public.seal_order_seals(TEXT);
CREATE FUNCTION public.seal_order_seals(p_order TEXT)
RETURNS TABLE (seg_status TEXT, start_code TEXT, end_code TEXT, qty BIGINT, al_number TEXT,
               customer_name TEXT, consent_at TIMESTAMPTZ, do_number TEXT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_al TEXT;
BEGIN
  FOREACH v_al IN ARRAY public.seal_order_als(p_order) LOOP
    RETURN QUERY SELECT g.seg_status, g.start_code, g.end_code, g.qty, g.al_number,
                        g.customer_name, g.consent_at, g.do_number
                   FROM public.seal_segments(v_al) g ORDER BY g.start_no;
  END LOOP;
END $$;

