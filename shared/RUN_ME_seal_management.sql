-- ============================================================================
-- MJM AI POWERED SYSTEM -- RUN_ME_seal_management.sql
--
-- SEAL MANAGEMENT. One paste, safe to run twice.
--
-- A seal is a barcode sticker like 0009297. It moves through four states:
--
--   In stock            received at UNN 1, from the Mobile Seal page
--   Pending collection  allocated to a customer when the consent is signed
--                       (start and end of each range scanned on Consent)
--   Scanned             scanned seal by seal at collection in the FC Portal,
--                       DO not issued yet
--   Collected           on a DO
--
-- What this file adds:
--   seal_settings             one row. enforce_stock is OFF until the seals
--                             already at UNN 1 have been keyed as opening stock
--   seal_orders               orders to the seal supplier (AI system)
--   seal_receipts             a delivery received at UNN 1, with photos
--   seal_receipt_ranges       its ranges, one row each
--   seal_allocations          ranges given to a customer on a consent
--   seal_problems             every problem found, and the NELOS case for it
--   mobile_consent_records    + seal_ranges, seal_photo_url
--   shared_do_records         + seal_ranges, seal_qty
--   fcportal_scan_records     + seal_no, do_number
--
-- THE CHECKS LIVE HERE, NOT ON THE PHONE. A phone with signal asks
-- seal_check_range() first and warns. A phone with no signal saves anyway, and
-- when the record finally arrives the triggers below check it. A problem is
-- never a refused row -- what the customer signed is kept -- it is a row in
-- seal_problems and a NELOS case to HQ.
--
-- HQ in NELOS is the system whose people see every case (sees_all_cases,
-- Nursery Operation). A seal case is put in that queue with NOBODY assigned,
-- so every HQ handler sees it and any of them can take it.
--
-- Seal numbers are compared as NUMBERS (0009297 and 9297 are one seal) and
-- shown in the width they were scanned in.
-- ============================================================================


-- ── 1. HELPERS ───────────────────────────────────────────────────────────────

-- The digits of a code, everything else dropped. Written with translate
-- because the SQL Editor has choked on regular expressions before.
CREATE OR REPLACE FUNCTION public.seal_digits(p TEXT)
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
  SELECT NULLIF(translate(COALESCE(p, ''), translate(COALESCE(p, ''), '0123456789', ''), ''), '')
$$;

-- The number a code stands for, or NULL. Longer than 15 digits is not a seal.
CREATE OR REPLACE FUNCTION public.seal_no(p TEXT)
RETURNS BIGINT LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN length(public.seal_digits(p)) BETWEEN 1 AND 15
              THEN public.seal_digits(p)::BIGINT END
$$;

-- A number written back at a width.
CREATE OR REPLACE FUNCTION public.seal_code(n BIGINT, w INT)
RETURNS TEXT LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN n IS NULL THEN NULL
              WHEN length(n::TEXT) >= COALESCE(w, 0) THEN n::TEXT
              ELSE lpad(n::TEXT, w, '0') END
$$;

-- Staff, as every other gate in this system reads it: a profile that is not a
-- customer. Sales Web customers sign in to the same project, so being signed
-- in is not enough to read who holds which seal.
CREATE OR REPLACE FUNCTION public.seal_is_staff()
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.shared_profiles p
     WHERE p.id = auth.uid()
       AND COALESCE(to_jsonb(p) ->> 'user_type', 'system') <> 'customer')
$$;


