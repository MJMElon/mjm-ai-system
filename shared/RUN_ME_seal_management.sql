-- ── 3. NELOS: a case to HQ ───────────────────────────────────────────────────
-- One open case per customer order and kind of problem. A second problem of
-- the same kind on the same AL is a comment on the case already open, so a
-- wrong roll scanned seal by seal is one case with a list, not two hundred.

CREATE OR REPLACE FUNCTION public.seal_raise_case(p_id BIGINT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  pr        public.seal_problems%ROWTYPE;
  v_case    BIGINT;
  v_module  TEXT;
  v_title   TEXT;
  v_body    TEXT;
BEGIN
  IF to_regclass('public.nelos_cases') IS NULL THEN RETURN NULL; END IF;
  SELECT * INTO pr FROM public.seal_problems WHERE id = p_id;
  IF NOT FOUND THEN RETURN NULL; END IF;

  v_body := pr.detail;

  SELECT c.id INTO v_case
    FROM public.seal_problems q
    JOIN public.nelos_cases c ON c.id = q.nelos_case_id
   WHERE q.id <> pr.id
     AND q.kind = pr.kind
     AND q.al_number IS NOT DISTINCT FROM pr.al_number
     AND q.receipt_id IS NOT DISTINCT FROM pr.receipt_id
     AND q.delivery_id IS NOT DISTINCT FROM pr.delivery_id
     AND c.status IN ('open', 'in_progress')
   ORDER BY c.id DESC
   LIMIT 1;

  IF v_case IS NOT NULL THEN
    INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
    VALUES (v_case, v_body, 'comment', 'Seal check (system)');
    UPDATE public.seal_problems SET nelos_case_id = v_case WHERE id = pr.id;
    RETURN v_case;
  END IF;

  SELECT NULLIF(s.nelos_module, '') INTO v_module FROM public.seal_settings s WHERE s.id = 1;
  IF v_module IS NULL AND to_regclass('public.nelos_modules') IS NOT NULL THEN
    SELECT m.key INTO v_module
      FROM public.nelos_modules m
     WHERE COALESCE((to_jsonb(m) ->> 'sees_all_cases')::BOOLEAN, false)
     ORDER BY m.sort_order
     LIMIT 1;
  END IF;
  v_module := COALESCE(v_module, 'nursery_ops');

  v_title := CASE pr.kind
    WHEN 'consent_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' given twice, already with ' || COALESCE(pr.other_customer, '?') || ' (' || COALESCE(pr.other_al, '?') || ')'
    WHEN 'consent_not_received' THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' were never received'
    WHEN 'consent_bad_range'    THEN 'Seal range could not be read on a consent'
    WHEN 'receive_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' received twice'
    WHEN 'collect_other'        THEN 'Seal ' || pr.seal_from || ' of ' || COALESCE(pr.other_customer, '?') || ' (' || COALESCE(pr.other_al, '?') || ') collected for another customer'
    WHEN 'collect_not_issued'   THEN 'Seal ' || pr.seal_from || ' collected but on no consent'
    WHEN 'hq_receive_overlap'   THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' received at HQ twice'
    WHEN 'deliver_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' sent to site twice'
    WHEN 'delivery_mismatch'    THEN 'Delivery #' || COALESCE(pr.delivery_id::TEXT, '?') || ' received at site does not match what HQ sent'
    WHEN 'delivery_twice'       THEN 'Delivery #' || COALESCE(pr.delivery_id::TEXT, '?') || ' confirmed received twice'
    WHEN 'missed_scan'          THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' not scanned, the seals either side are on a DO'
    ELSE 'Seal problem' END;
  IF pr.al_number IS NOT NULL THEN
    v_title := v_title || ', for ' || COALESCE(pr.customer_name, '?') || ' (' || pr.al_number || ')';
  END IF;

  INSERT INTO public.nelos_cases
    (title, description, category, priority, status, source_module, assigned_module,
     source_ref, nursery_name, raised_by)
  VALUES
    (left(v_title, 300),
     v_body || ' Pending action: check the seals and correct the record.',
     'Seal', 'high', 'open', 'seal', v_module,
     '../seal/seal_dashboard.html?tab=problems&problem=' || pr.id,
     (SELECT site FROM public.seal_settings WHERE id = 1),
     'Seal check (system)')
  RETURNING id INTO v_case;

  INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
  VALUES (v_case, v_body, 'comment', 'Seal check (system)');

  UPDATE public.seal_problems SET nelos_case_id = v_case WHERE id = pr.id;
  RETURN v_case;
EXCEPTION WHEN OTHERS THEN
  -- A NELOS that will not take the case must never refuse the consent, the
  -- receipt or the scan. The problem row is kept and says so.
  UPDATE public.seal_problems
     SET detail = detail || ' [NELOS case not opened: ' || SQLERRM || ']'
   WHERE id = p_id;
  RETURN NULL;
END $$;

-- Seal as a NELOS system, so a case can say it came from here, and the Seal
-- category, so it is filed under something.
DO $cat$
BEGIN
  IF to_regclass('public.nelos_modules') IS NOT NULL THEN
    INSERT INTO public.nelos_modules (key, label, icon, href, sort_order, active)
    SELECT 'seal', 'Seal Manage', '🔖', '../seal/seal_dashboard.html', 60, true
     WHERE NOT EXISTS (SELECT 1 FROM public.nelos_modules WHERE key = 'seal');
  END IF;
  -- The title carries its SYSTEM and the CONDITION that raises it, because
  -- a title with neither is on no screen the office reads: both raise forms
  -- scope the Work list on module_key, and Automate Cases lists exactly the
  -- titles carrying an auto_condition. The first version of this insert set
  -- neither, and the busiest automatic title in the database was invisible
  -- on both -- RUN_ME_seal_case_category.sql repairs a database already
  -- running. Through EXECUTE because an older nelos_categories may have
  -- neither column, and a plain statement naming one fails at parse.
  IF to_regclass('public.nelos_categories') IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema='public' AND table_name='nelos_categories'
                  AND column_name='module_key')
       AND EXISTS (SELECT 1 FROM information_schema.columns
                    WHERE table_schema='public' AND table_name='nelos_categories'
                      AND column_name='auto_condition') THEN
      EXECUTE $q$
        INSERT INTO public.nelos_categories (name, module_key, sort_order, default_priority, auto_condition)
        SELECT 'Seal', 'seal', 90, 'high',
               'A seal check finds a problem: a range given twice, a range never received, '
               'a range that could not be read, a range received twice, a seal collected '
               'for another customer, or a seal collected on no consent'
         WHERE NOT EXISTS (SELECT 1 FROM public.nelos_categories WHERE lower(name) = 'seal')
      $q$;
    ELSE
      INSERT INTO public.nelos_categories (name, sort_order, default_priority)
      SELECT 'Seal', 90, 'high'
       WHERE NOT EXISTS (SELECT 1 FROM public.nelos_categories WHERE name = 'Seal');
    END IF;
  END IF;
END $cat$;

CREATE OR REPLACE FUNCTION public.seal_add_problem(
  p_kind TEXT, p_consent TEXT, p_receipt BIGINT, p_al TEXT, p_customer TEXT,
  p_from TEXT, p_to TEXT, p_qty BIGINT, p_other_al TEXT, p_other_customer TEXT, p_detail TEXT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id BIGINT;
BEGIN
  INSERT INTO public.seal_problems
    (kind, consent_id, receipt_id, al_number, customer_name, seal_from, seal_to, qty,
     other_al, other_customer, detail)
  VALUES
    (p_kind, p_consent, p_receipt, p_al, p_customer, p_from, p_to, p_qty,
     p_other_al, p_other_customer, p_detail)
  RETURNING id INTO v_id;
  PERFORM public.seal_raise_case(v_id);
  RETURN v_id;
END $$;


-- ── 4. CONSENT: ranges become allocations, and are checked ───────────────────
-- seal_ranges on the consent is [{"start":"0009001","end":"0009600"}, ...].
-- The consent row is what the phone saves, online or from its outbox, so this
-- is the one place every consent passes through.

CREATE OR REPLACE FUNCTION public.seal_sync_consent()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  el        JSONB;
  v_s       TEXT;
  v_e       TEXT;
  n1        BIGINT;
  n2        BIGINT;
  t         BIGINT;
  w         INT;
  hit       RECORD;
  v_cov     BIGINT;
  v_enforce BOOLEAN;
  v_cid     TEXT := NEW.id::TEXT;
  v_cust    TEXT := NEW.customer_name;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.seal_ranges IS NOT DISTINCT FROM OLD.seal_ranges THEN
    RETURN NEW;
  END IF;

  DELETE FROM public.seal_allocations WHERE consent_id = v_cid;
  IF NEW.seal_ranges IS NULL OR jsonb_typeof(NEW.seal_ranges) <> 'array' THEN
    RETURN NEW;
  END IF;

  SELECT enforce_stock INTO v_enforce FROM public.seal_settings WHERE id = 1;

  FOR el IN SELECT * FROM jsonb_array_elements(NEW.seal_ranges) LOOP
    v_s := el ->> 'start';
    v_e := COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start');
    n1 := public.seal_no(v_s);
    n2 := public.seal_no(v_e);
    IF n1 IS NULL OR n2 IS NULL THEN
      PERFORM public.seal_add_problem('consent_bad_range', v_cid, NULL, NEW.al_number, v_cust,
        v_s, v_e, NULL, NULL, NULL,
        'Consent ' || v_cid || ' carries a seal range that is not a number: ' || COALESCE(v_s, '?') || ' to ' || COALESCE(v_e, '?') || '.');
      CONTINUE;
    END IF;
    IF n2 < n1 THEN t := n1; n1 := n2; n2 := t; t := NULL; v_s := v_e; END IF;
    w := GREATEST(length(public.seal_digits(v_s)), length(public.seal_digits(v_e)));

    -- Another consent already holds part of it.
    FOR hit IN
      SELECT a.*, GREATEST(a.start_no, n1) AS o1, LEAST(a.end_no, n2) AS o2
        FROM public.seal_allocations a
       WHERE a.consent_id <> v_cid AND a.start_no <= n2 AND a.end_no >= n1
    LOOP
      PERFORM public.seal_add_problem('consent_overlap', v_cid, NULL, NEW.al_number, v_cust,
        public.seal_code(hit.o1, w), public.seal_code(hit.o2, w), hit.o2 - hit.o1 + 1,
        hit.al_number, hit.customer_name,
        'Seals ' || public.seal_code(hit.o1, w) || ' - ' || public.seal_code(hit.o2, w)
          || ' (' || (hit.o2 - hit.o1 + 1) || ') were allocated to ' || COALESCE(v_cust, '?')
          || ' (' || COALESCE(NEW.al_number, '?') || ') but already belong to '
          || COALESCE(hit.customer_name, '?') || ' (' || COALESCE(hit.al_number, '?') || ').');
    END LOOP;

    -- Never received at UNN 1. Only once the opening stock is in.
    IF COALESCE(v_enforce, false) THEN
      SELECT COALESCE(sum(LEAST(r.end_no, n2) - GREATEST(r.start_no, n1) + 1), 0) INTO v_cov
        FROM public.seal_receipt_ranges r
       WHERE r.start_no <= n2 AND r.end_no >= n1;
      IF v_cov < n2 - n1 + 1 THEN
        PERFORM public.seal_add_problem('consent_not_received', v_cid, NULL, NEW.al_number, v_cust,
          public.seal_code(n1, w), public.seal_code(n2, w), (n2 - n1 + 1) - v_cov, NULL, NULL,
          ((n2 - n1 + 1) - v_cov) || ' of the seals ' || public.seal_code(n1, w) || ' - '
            || public.seal_code(n2, w) || ' allocated to ' || COALESCE(v_cust, '?')
            || ' were never received at UNN 1.');
      END IF;
    END IF;

    INSERT INTO public.seal_allocations
      (consent_id, al_number, order_number, customer_name, start_code, end_code, start_no, end_no, consent_at)
    VALUES
      (v_cid, NEW.al_number, NEW.order_number, v_cust,
       public.seal_code(n1, w), public.seal_code(n2, w), n1, n2, NEW.created_at);
  END LOOP;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS seal_sync_consent ON public.mobile_consent_records;
CREATE TRIGGER seal_sync_consent
  AFTER INSERT OR UPDATE OF seal_ranges ON public.mobile_consent_records
  FOR EACH ROW EXECUTE FUNCTION public.seal_sync_consent();

CREATE OR REPLACE FUNCTION public.seal_drop_consent()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  DELETE FROM public.seal_allocations WHERE consent_id = OLD.id::TEXT;
  RETURN OLD;
END $$;

DROP TRIGGER IF EXISTS seal_drop_consent ON public.mobile_consent_records;
CREATE TRIGGER seal_drop_consent
  AFTER DELETE ON public.mobile_consent_records
  FOR EACH ROW EXECUTE FUNCTION public.seal_drop_consent();


-- ── 5. RECEIVE: ranges become stock, and are checked ─────────────────────────

CREATE OR REPLACE FUNCTION public.seal_sync_receipt()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  el   JSONB;
  v_s  TEXT;
  v_e  TEXT;
  n1   BIGINT;
  n2   BIGINT;
  t    BIGINT;
  w    INT;
  hit  RECORD;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.ranges IS NOT DISTINCT FROM OLD.ranges THEN
    RETURN NEW;
  END IF;
  DELETE FROM public.seal_receipt_ranges WHERE receipt_id = NEW.id;
  IF NEW.ranges IS NULL OR jsonb_typeof(NEW.ranges) <> 'array' THEN RETURN NEW; END IF;

  FOR el IN SELECT * FROM jsonb_array_elements(NEW.ranges) LOOP
    v_s := el ->> 'start';
    v_e := COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start');
    n1 := public.seal_no(v_s);
    n2 := public.seal_no(v_e);
    CONTINUE WHEN n1 IS NULL OR n2 IS NULL;
    IF n2 < n1 THEN t := n1; n1 := n2; n2 := t; v_s := v_e; END IF;
    w := GREATEST(length(public.seal_digits(v_s)), length(public.seal_digits(v_e)));

    FOR hit IN
      SELECT r.receipt_id, GREATEST(r.start_no, n1) AS o1, LEAST(r.end_no, n2) AS o2
        FROM public.seal_receipt_ranges r
       WHERE r.receipt_id <> NEW.id AND r.start_no <= n2 AND r.end_no >= n1
    LOOP
      PERFORM public.seal_add_problem('receive_overlap', NULL, NEW.id, NULL, NULL,
        public.seal_code(hit.o1, w), public.seal_code(hit.o2, w), hit.o2 - hit.o1 + 1, NULL, NULL,
        'Seals ' || public.seal_code(hit.o1, w) || ' - ' || public.seal_code(hit.o2, w)
          || ' on receipt ' || NEW.id || ' were already received on receipt ' || hit.receipt_id || '.');
    END LOOP;

    INSERT INTO public.seal_receipt_ranges (receipt_id, start_code, end_code, start_no, end_no)
    VALUES (NEW.id, public.seal_code(n1, w), public.seal_code(n2, w), n1, n2);
  END LOOP;
  RETURN NEW;
END $$;

