CREATE OR REPLACE FUNCTION public.seal_check_scan()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  own   RECORD;
  other RECORD;
  v_cust TEXT;
BEGIN
  IF NEW.seal_no IS NULL OR NEW.al_number IS NULL THEN RETURN NEW; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.seal_allocations WHERE al_number = NEW.al_number) THEN
    RETURN NEW;
  END IF;
  IF EXISTS (SELECT 1 FROM public.seal_allocations a
              WHERE a.al_number = NEW.al_number
                AND NEW.seal_no BETWEEN a.start_no AND a.end_no) THEN
    RETURN NEW;
  END IF;

  SELECT customer_name INTO v_cust FROM public.seal_allocations
   WHERE al_number = NEW.al_number ORDER BY id LIMIT 1;

  SELECT * INTO other FROM public.seal_allocations a
   WHERE a.al_number IS DISTINCT FROM NEW.al_number
     AND NEW.seal_no BETWEEN a.start_no AND a.end_no
   ORDER BY a.id LIMIT 1;

  IF FOUND THEN
    PERFORM public.seal_add_problem('collect_other', NEW.consent_id::TEXT, NULL, NEW.al_number, v_cust,
      NEW.barcode, NEW.barcode, 1, other.al_number, other.customer_name,
      'Seal ' || NEW.barcode || ' was scanned at collection for ' || COALESCE(v_cust, '?')
        || ' (' || NEW.al_number || ') but it belongs to ' || COALESCE(other.customer_name, '?')
        || ' (' || COALESCE(other.al_number, '?') || ').');
  ELSE
    PERFORM public.seal_add_problem('collect_not_issued', NEW.consent_id::TEXT, NULL, NEW.al_number, v_cust,
      NEW.barcode, NEW.barcode, 1, NULL, NULL,
      'Seal ' || NEW.barcode || ' was scanned at collection for ' || COALESCE(v_cust, '?')
        || ' (' || NEW.al_number || ') but it is on no consent.');
  END IF;
  RETURN NEW;
END $$;

