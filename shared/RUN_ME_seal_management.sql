-- A scan that arrives AFTER its DO (scanned offline, DO sent first) finds the
-- DO that already names it.
CREATE OR REPLACE FUNCTION public.seal_scan_do()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  -- Triggers of one kind fire in name order, so seal_scan_do runs BEFORE
  -- seal_scan_number and cannot lean on it. It works the number out itself.
  NEW.seal_no := public.seal_no(NEW.barcode);
  IF NEW.seal_no IS NULL OR NEW.do_number IS NOT NULL THEN RETURN NEW; END IF;
  SELECT d.do_number INTO NEW.do_number
    FROM public.shared_do_records d, jsonb_array_elements(d.seal_ranges) el
   WHERE d.al_number = NEW.al_number
     AND jsonb_typeof(d.seal_ranges) = 'array'
     AND NEW.seal_no BETWEEN LEAST(public.seal_no(el ->> 'start'), public.seal_no(COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start')))
                         AND GREATEST(public.seal_no(el ->> 'start'), public.seal_no(COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start')))
   LIMIT 1;
  RETURN NEW;
END $$;

