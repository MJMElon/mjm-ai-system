-- ── 7. DO: the seals on it are collected ─────────────────────────────────────
-- seal_ranges on the DO is [{"start":"0009001","end":"0009600","qty":600}, ...]
-- written by the FC Portal from the seals scanned since the last DO.

CREATE OR REPLACE FUNCTION public.seal_sync_do()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE el JSONB; n1 BIGINT; n2 BIGINT;
BEGIN
  IF NEW.seal_ranges IS NULL OR jsonb_typeof(NEW.seal_ranges) <> 'array' THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' THEN
    UPDATE public.fcportal_scan_records SET do_number = NULL
     WHERE do_number = OLD.do_number AND al_number IS NOT DISTINCT FROM NEW.al_number;
  END IF;
  FOR el IN SELECT * FROM jsonb_array_elements(NEW.seal_ranges) LOOP
    n1 := public.seal_no(el ->> 'start');
    n2 := public.seal_no(COALESCE(NULLIF(el ->> 'end', ''), el ->> 'start'));
    CONTINUE WHEN n1 IS NULL OR n2 IS NULL;
    UPDATE public.fcportal_scan_records
       SET do_number = NEW.do_number
     WHERE al_number = NEW.al_number
       AND seal_no BETWEEN LEAST(n1, n2) AND GREATEST(n1, n2)
       AND (do_number IS NULL OR do_number = NEW.do_number);
  END LOOP;
  RETURN NEW;
END $$;

