-- ── 6. THE GAPS ALREADY THERE ────────────────────────────────────────────────
-- Every customer, every gap: a problem and a NELOS case each, once. Running
-- this file again raises nothing new for a gap already raised.
SELECT public.seal_flag_missed(NULL);

NOTIFY pgrst, 'reload schema';

-- ── 7. CHECK ─────────────────────────────────────────────────────────────────
-- A good result is 8 rows. The first six read OK. gaps found now is how many
-- runs of unscanned seals sit between seals on a DO -- each should have an open
-- problem, so the two counts under it match. settled so far is how many the
-- office has keyed a DO for.
SELECT 'table seal_settled_scans' AS item,
       CASE WHEN to_regclass('public.seal_settled_scans') IS NOT NULL THEN 'OK' ELSE 'MISSING' END AS result,
       (SELECT count(*) FROM public.seal_settled_scans)::TEXT AS detail
UNION ALL SELECT 'trigger on DO for gaps', CASE WHEN EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'seal_sync_do_missed') THEN 'OK' ELSE 'MISSING' END, ''
UNION ALL SELECT 'function seal_settle_scan', CASE WHEN to_regprocedure('public.seal_settle_scan(text,text,text,text,text,text,bigint)') IS NOT NULL THEN 'OK' ELSE 'MISSING' END, ''
UNION ALL SELECT 'function seal_missed_scans', CASE WHEN to_regprocedure('public.seal_missed_scans()') IS NOT NULL THEN 'OK' ELSE 'MISSING' END, ''
UNION ALL SELECT 'seal_segments reads settled seals', CASE WHEN position('seal_settled_scans' in pg_get_functiondef('public.seal_segments(text)'::regprocedure)) > 0 THEN 'OK' ELSE 'OLD' END, ''
UNION ALL SELECT 'case title for a missed scan', CASE WHEN position('missed_scan' in pg_get_functiondef('public.seal_raise_case(bigint)'::regprocedure)) > 0 THEN 'OK' ELSE 'OLD' END, ''
UNION ALL SELECT 'gaps found now', 'OK', (SELECT count(*) FROM public.seal_find_missed(NULL))::TEXT || ' runs, '
       || COALESCE((SELECT sum(qty) FROM public.seal_find_missed(NULL)), 0)::TEXT || ' seals'
UNION ALL SELECT 'open missed-scan problems', 'OK',
       (SELECT count(*) FROM public.seal_problems WHERE kind = 'missed_scan' AND status = 'open')::TEXT
       || ' open, ' || (SELECT count(DISTINCT nelos_case_id) FROM public.seal_problems WHERE kind = 'missed_scan' AND status = 'open')::TEXT || ' NELOS cases';
