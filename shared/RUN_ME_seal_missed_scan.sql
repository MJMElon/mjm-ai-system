-- ============================================================================
-- MJM AI POWERED SYSTEM -- RUN_ME_seal_missed_scan.sql
--
-- SEAL MANAGE: SEALS THE FC PORTAL NEVER SCANNED. One paste, safe to run twice.
-- Run it AFTER RUN_ME_seal_management.sql and RUN_ME_seal_hq_delivery.sql.
--
-- A seal is collected when the FC Portal scans it and a DO names it. A seal
-- that went out on the truck and was never scanned stays Pending collection
-- for ever, with the seals either side of it already on a DO -- which is
-- exactly how the office found these.
--
--   1. The system FINDS them: a run of pending seals with the seal just before
--      and the seal just after both on a DO, same customer. Each one gets a
--      seal problem and a NELOS case to HQ, the same as every seal problem.
--   2. The office SETTLES them on Seal Manage: key the DO they went out on,
--      or say they did not go. seal_settle_scan checks the range, the
--      customer and the DO, writes seal_settled_scans, adds the seals to that
--      DO seal list, and resolves the problem and its case.
--   3. A delivered settled range reads as Used on that DO everywhere a seal
--      status is read, because seal_segments counts it as scanned on it.
--
-- The same settle works on any range of a customer seals that was never
-- scanned, gap or not -- the standard way to put a DO to a seal by hand.
--
-- seal_raise_case and seal_segments are copied here WORD FOR WORD from
-- RUN_ME_seal_management.sql, so running any of the three files leaves the
-- same functions. tests/seal_dashboard.cjs compares the copies.
-- ============================================================================


-- ── 1. THE TABLE ─────────────────────────────────────────────────────────────

-- Seals the office has SETTLED by hand because the FC Portal never scanned
-- them: a run of a customer seals with a gap nobody scanned, the seals either
-- side already on a DO. The office keys the DO they went out on, or says they
-- did not go. seal_segments reads a delivered row as if it were scanned on
-- that DO. RUN_ME_seal_missed_scan.sql is what writes them.
CREATE TABLE IF NOT EXISTS public.seal_settled_scans (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  al_number     TEXT NOT NULL,
  customer_name TEXT,
  start_code    TEXT NOT NULL,
  end_code      TEXT NOT NULL,
  start_no      BIGINT NOT NULL,
  end_no        BIGINT NOT NULL,
  qty           BIGINT GENERATED ALWAYS AS (end_no - start_no + 1) STORED,
  outcome       TEXT NOT NULL CHECK (outcome IN ('delivered', 'not_delivered')),
  do_number     TEXT,
  remark        TEXT,
  problem_id    BIGINT,
  settled_by    TEXT,
  settled_by_id UUID,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (end_no >= start_no)
);
CREATE INDEX IF NOT EXISTS seal_settled_scans_al_idx ON public.seal_settled_scans (al_number, start_no);


-- ── 2. THE CASE TITLE AND THE SEAL STATUS ────────────────────────────────────

CREATE OR REPLACE FUNCTION public.seal_raise_case(p_id BIGINT)
RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  pr        public.seal_problems%ROWTYPE;
  v_case    BIGINT;
  v_module  TEXT;
  v_title   TEXT;
  v_body    TEXT;
BEGIN
  IF to_regclass('public.nelos_cases') IS NULL THEN RETURN NULL; END IF;
  SELECT * INTO pr FROM public.seal_problems WHERE id = p_id;
  IF NOT FOUND THEN RETURN NULL; END IF;

  v_body := pr.detail;

  SELECT c.id INTO v_case
    FROM public.seal_problems q
    JOIN public.nelos_cases c ON c.id = q.nelos_case_id
   WHERE q.id <> pr.id
     AND q.kind = pr.kind
     AND q.al_number IS NOT DISTINCT FROM pr.al_number
     AND q.receipt_id IS NOT DISTINCT FROM pr.receipt_id
     AND q.delivery_id IS NOT DISTINCT FROM pr.delivery_id
     AND c.status IN ('open', 'in_progress')
   ORDER BY c.id DESC
   LIMIT 1;

  IF v_case IS NOT NULL THEN
    INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
    VALUES (v_case, v_body, 'comment', 'Seal check (system)');
    UPDATE public.seal_problems SET nelos_case_id = v_case WHERE id = pr.id;
    RETURN v_case;
  END IF;

  SELECT NULLIF(s.nelos_module, '') INTO v_module FROM public.seal_settings s WHERE s.id = 1;
  IF v_module IS NULL AND to_regclass('public.nelos_modules') IS NOT NULL THEN
    SELECT m.key INTO v_module
      FROM public.nelos_modules m
     WHERE COALESCE((to_jsonb(m) ->> 'sees_all_cases')::BOOLEAN, false)
     ORDER BY m.sort_order
     LIMIT 1;
  END IF;
  v_module := COALESCE(v_module, 'nursery_ops');

  v_title := CASE pr.kind
    WHEN 'consent_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' given twice, already with ' || COALESCE(pr.other_customer, '?') || ' (' || COALESCE(pr.other_al, '?') || ')'
    WHEN 'consent_not_received' THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' were never received'
    WHEN 'consent_bad_range'    THEN 'Seal range could not be read on a consent'
    WHEN 'receive_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' received twice'
    WHEN 'collect_other'        THEN 'Seal ' || pr.seal_from || ' of ' || COALESCE(pr.other_customer, '?') || ' (' || COALESCE(pr.other_al, '?') || ') collected for another customer'
    WHEN 'collect_not_issued'   THEN 'Seal ' || pr.seal_from || ' collected but on no consent'
    WHEN 'hq_receive_overlap'   THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' received at HQ twice'
    WHEN 'deliver_overlap'      THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' sent to site twice'
    WHEN 'delivery_mismatch'    THEN 'Delivery #' || COALESCE(pr.delivery_id::TEXT, '?') || ' received at site does not match what HQ sent'
    WHEN 'delivery_twice'       THEN 'Delivery #' || COALESCE(pr.delivery_id::TEXT, '?') || ' confirmed received twice'
    WHEN 'missed_scan'          THEN 'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' not scanned, the seals either side are on a DO'
    ELSE 'Seal problem' END;
  IF pr.al_number IS NOT NULL THEN
    v_title := v_title || ', for ' || COALESCE(pr.customer_name, '?') || ' (' || pr.al_number || ')';
  END IF;

  INSERT INTO public.nelos_cases
    (title, description, category, priority, status, source_module, assigned_module,
     source_ref, nursery_name, raised_by)
  VALUES
    (left(v_title, 300),
     v_body || ' Pending action: check the seals and correct the record.',
     'Seal', 'high', 'open', 'seal', v_module,
     '../seal/seal_dashboard.html?tab=problems&problem=' || pr.id,
     (SELECT site FROM public.seal_settings WHERE id = 1),
     'Seal check (system)')
  RETURNING id INTO v_case;

  INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
  VALUES (v_case, v_body, 'comment', 'Seal check (system)');

  UPDATE public.seal_problems SET nelos_case_id = v_case WHERE id = pr.id;
  RETURN v_case;
EXCEPTION WHEN OTHERS THEN
  -- A NELOS that will not take the case must never refuse the consent, the
  -- receipt or the scan. The problem row is kept and says so.
  UPDATE public.seal_problems
     SET detail = detail || ' [NELOS case not opened: ' || SQLERRM || ']'
   WHERE id = p_id;
  RETURN NULL;
END $$;

-- Every range in the system, split by what has happened to each part of it.
-- seg_status: in_stock | pending | scanned | collected
CREATE OR REPLACE FUNCTION public.seal_segments(p_al TEXT DEFAULT NULL)
RETURNS TABLE (seg_status TEXT, start_code TEXT, end_code TEXT, start_no BIGINT, end_no BIGINT, qty BIGINT,
               al_number TEXT, customer_name TEXT, consent_id TEXT, consent_at TIMESTAMPTZ,
               do_number TEXT, allocation_id BIGINT, receipt_id BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  a    RECORD;
  isl  RECORD;
  r    RECORD;
  cur  BIGINT;
  w    INT;
BEGIN
  FOR a IN SELECT * FROM public.seal_allocations x
            WHERE p_al IS NULL OR x.al_number = p_al
            ORDER BY x.start_no LOOP
    w := length(a.start_code);
    cur := a.start_no;
    FOR isl IN
      SELECT g.do_number AS dn, min(g.seal_no) AS s, max(g.seal_no) AS e, count(*) AS n
        FROM (SELECT DISTINCT ON (f.seal_no) f.seal_no, f.do_number,
                     f.seal_no - dense_rank() OVER (PARTITION BY COALESCE(f.do_number, '') ORDER BY f.seal_no) AS grp
                FROM (SELECT x.seal_no, x.do_number FROM public.fcportal_scan_records x
                       WHERE x.al_number = a.al_number
                         AND x.seal_no BETWEEN a.start_no AND a.end_no
                      UNION ALL
                      -- a seal the office settled as delivered reads as scanned on its DO
                      SELECT gs.n, z.do_number
                        FROM public.seal_settled_scans z,
                             generate_series(GREATEST(z.start_no, a.start_no), LEAST(z.end_no, a.end_no)) AS gs(n)
                       WHERE z.al_number = a.al_number AND z.outcome = 'delivered'
                         AND z.start_no <= a.end_no AND z.end_no >= a.start_no) f
               ORDER BY f.seal_no, f.do_number NULLS LAST) g
       GROUP BY g.do_number, g.grp
       ORDER BY min(g.seal_no)
    LOOP
      IF isl.s > cur THEN
        RETURN QUERY SELECT 'pending'::TEXT, public.seal_code(cur, w), public.seal_code(isl.s - 1, w), cur, isl.s - 1,
          isl.s - cur, a.al_number, a.customer_name, a.consent_id, a.consent_at, NULL::TEXT, a.id, NULL::BIGINT;
      END IF;
      RETURN QUERY SELECT CASE WHEN isl.dn IS NULL THEN 'scanned' ELSE 'collected' END,
        public.seal_code(isl.s, w), public.seal_code(isl.e, w), isl.s, isl.e, isl.n,
        a.al_number, a.customer_name, a.consent_id, a.consent_at, isl.dn, a.id, NULL::BIGINT;
      cur := GREATEST(cur, isl.e + 1);
    END LOOP;
    IF cur <= a.end_no THEN
      RETURN QUERY SELECT 'pending'::TEXT, public.seal_code(cur, w), public.seal_code(a.end_no, w), cur, a.end_no,
        a.end_no - cur + 1, a.al_number, a.customer_name, a.consent_id, a.consent_at, NULL::TEXT, a.id, NULL::BIGINT;
    END IF;
  END LOOP;

  IF p_al IS NOT NULL THEN RETURN; END IF;

  -- What was received and is on no consent is in stock.
  FOR r IN SELECT x.*, s.received_date FROM public.seal_receipt_ranges x
             JOIN public.seal_receipts s ON s.id = x.receipt_id
            ORDER BY x.start_no LOOP
    w := length(r.start_code);
    cur := r.start_no;
    FOR a IN SELECT x.start_no AS s, x.end_no AS e FROM public.seal_allocations x
              WHERE x.start_no <= r.end_no AND x.end_no >= r.start_no
              ORDER BY x.start_no LOOP
      IF a.s > cur THEN
        RETURN QUERY SELECT 'in_stock'::TEXT, public.seal_code(cur, w), public.seal_code(LEAST(a.s - 1, r.end_no), w),
          cur, LEAST(a.s - 1, r.end_no), LEAST(a.s - 1, r.end_no) - cur + 1,
          NULL::TEXT, NULL::TEXT, NULL::TEXT, r.received_date::TIMESTAMPTZ, NULL::TEXT, NULL::BIGINT, r.receipt_id;
      END IF;
      cur := GREATEST(cur, a.e + 1);
    END LOOP;
    IF cur <= r.end_no THEN
      RETURN QUERY SELECT 'in_stock'::TEXT, public.seal_code(cur, w), public.seal_code(r.end_no, w),
        cur, r.end_no, r.end_no - cur + 1,
        NULL::TEXT, NULL::TEXT, NULL::TEXT, r.received_date::TIMESTAMPTZ, NULL::TEXT, NULL::BIGINT, r.receipt_id;
    END IF;
  END LOOP;
END $$;

-- ── 3. FINDING A SEAL NOBODY SCANNED ─────────────────────────────────────────
-- A gap is a run of a customer seals still pending collection with a seal on a
-- DO immediately before it AND immediately after it, the same customer on both
-- sides. The FC Portal scans every seal as it goes out, so seals that went out
-- in the middle of a load and were never scanned read exactly like this. A
-- range the office has already settled, either way, is never a gap again.
-- Internal: the trigger calls it as whoever saved the DO.
DROP FUNCTION IF EXISTS public.seal_find_missed(TEXT);
CREATE FUNCTION public.seal_find_missed(p_al TEXT DEFAULT NULL)
RETURNS TABLE (al_number TEXT, customer_name TEXT, start_code TEXT, end_code TEXT,
               start_no BIGINT, end_no BIGINT, qty BIGINT, do_before TEXT, do_after TEXT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
BEGIN
  RETURN QUERY
    WITH seg AS (
      SELECT g.*,
             lag(g.seg_status) OVER w AS p_st, lag(g.end_no) OVER w AS p_end, lag(g.do_number) OVER w AS p_do,
             lead(g.seg_status) OVER w AS n_st, lead(g.start_no) OVER w AS n_start, lead(g.do_number) OVER w AS n_do
        FROM public.seal_segments(p_al) g
       WHERE g.al_number IS NOT NULL
      WINDOW w AS (PARTITION BY g.al_number ORDER BY g.start_no)
    )
    SELECT s.al_number::TEXT, s.customer_name::TEXT, s.start_code::TEXT, s.end_code::TEXT,
           s.start_no::BIGINT, s.end_no::BIGINT, s.qty::BIGINT, s.p_do::TEXT, s.n_do::TEXT
      FROM seg s
     WHERE s.seg_status = 'pending'
       AND s.p_st = 'collected' AND s.p_end + 1 = s.start_no
       AND s.n_st = 'collected' AND s.n_start = s.end_no + 1
       AND NOT EXISTS (SELECT 1 FROM public.seal_settled_scans z
                        WHERE z.al_number = s.al_number
                          AND z.start_no <= s.end_no AND z.end_no >= s.start_no)
     ORDER BY s.al_number, s.start_no;
END $$;

-- A case is settled when nothing filed on it is still open. Never refuses.
CREATE OR REPLACE FUNCTION public.seal_close_case_if_done(p_case BIGINT, p_note TEXT, p_by TEXT)
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF p_case IS NULL OR to_regclass('public.nelos_cases') IS NULL THEN RETURN; END IF;
  IF p_note IS NOT NULL THEN
    INSERT INTO public.nelos_case_comments (case_id, body, kind, author_name)
    VALUES (p_case, p_note, 'comment', COALESCE(p_by, 'Seal check (system)'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.seal_problems WHERE nelos_case_id = p_case AND status = 'open') THEN
    UPDATE public.nelos_cases SET status = 'resolved'
     WHERE id = p_case AND status IN ('open', 'in_progress', 'pending');
  END IF;
EXCEPTION WHEN OTHERS THEN
  RETURN;
END $$;

-- Every gap gets a problem and a NELOS case to HQ, once. A gap that is no
-- longer one -- scanned after all, or settled -- has its problem resolved, and
-- its case with it when nothing else is open on it.
CREATE OR REPLACE FUNCTION public.seal_flag_missed(p_al TEXT DEFAULT NULL)
RETURNS INT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  m   RECORD;
  pr  RECORD;
  n   INT := 0;
BEGIN
  FOR m IN SELECT * FROM public.seal_find_missed(p_al) LOOP
    IF NOT EXISTS (SELECT 1 FROM public.seal_problems p
                    WHERE p.kind = 'missed_scan' AND p.status = 'open'
                      AND p.al_number = m.al_number
                      AND p.seal_from = m.start_code AND p.seal_to = m.end_code) THEN
      PERFORM public.seal_add_problem('missed_scan', NULL, NULL, m.al_number, m.customer_name,
        m.start_code, m.end_code, m.qty, NULL, NULL,
        'Seals ' || m.start_code || ' - ' || m.end_code || ' (' || m.qty || ') of '
          || COALESCE(m.customer_name, '?') || ' (' || m.al_number || ') were never scanned at collection, '
          || 'but the seal before them is on DO ' || COALESCE(m.do_before, '?')
          || ' and the seal after them is on DO ' || COALESCE(m.do_after, '?') || '. '
          || 'Check whether they went out, then key the DO for them in Seal Manage, NELOS tab, Seals not scanned.');
      n := n + 1;
    END IF;
  END LOOP;
  FOR pr IN SELECT p.* FROM public.seal_problems p
             WHERE p.kind = 'missed_scan' AND p.status = 'open'
               AND (p_al IS NULL OR p.al_number = p_al)
               AND NOT EXISTS (SELECT 1 FROM public.seal_find_missed(p.al_number) f
                                WHERE f.start_code = p.seal_from AND f.end_code = p.seal_to) LOOP
    UPDATE public.seal_problems
       SET status = 'resolved', resolution = 'No longer a gap: scanned after all, or settled',
           resolved_by = 'Seal check (system)', resolved_at = now()
     WHERE id = pr.id;
    PERFORM public.seal_close_case_if_done(pr.nelos_case_id,
      'Seals ' || pr.seal_from || ' - ' || pr.seal_to || ' are no longer a gap: scanned after all, or settled.', NULL);
  END LOOP;
  RETURN n;
END $$;

-- A DO is when a gap appears: the seals on either side of it have just gone
-- out. Named to sort AFTER seal_sync_do, so the scans already carry the DO.
CREATE OR REPLACE FUNCTION public.seal_sync_do_missed()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.al_number IS NOT NULL THEN PERFORM public.seal_flag_missed(NEW.al_number); END IF;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  -- A check that fails must never refuse the DO.
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS seal_sync_do_missed ON public.shared_do_records;
CREATE TRIGGER seal_sync_do_missed
  AFTER INSERT OR UPDATE OF seal_ranges, do_number ON public.shared_do_records
  FOR EACH ROW EXECUTE FUNCTION public.seal_sync_do_missed();


-- ── 4. SETTLING IT: THE OFFICE KEYS THE DO ───────────────────────────────────
-- The standard way to close seals the FC Portal never scanned, gap or not:
-- name the customer, the range, and either the DO they went out on, or that
-- they did not go. Every check is here, not on the page:
--   the range is a range, smallest first
--   every seal of it is on a consent of THIS customer
--   none of it was scanned (a scanned seal already has its answer)
--   none of it was settled before
--   a delivered range names a DO that belongs to THIS customer
-- A delivered range is added to that DO seal list as well, marked settled, so
-- the DO says which seals it carried. The open problem on the range is
-- resolved, and its NELOS case with it when nothing else is open on it.
DROP FUNCTION IF EXISTS public.seal_settle_scan(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, BIGINT);
CREATE FUNCTION public.seal_settle_scan(p_al TEXT, p_start TEXT, p_end TEXT, p_outcome TEXT,
                                        p_do TEXT DEFAULT NULL, p_remark TEXT DEFAULT NULL,
                                        p_problem BIGINT DEFAULT NULL)
RETURNS TEXT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  n1      BIGINT := public.seal_no(p_start);
  n2      BIGINT := public.seal_no(COALESCE(NULLIF(trim(p_end), ''), p_start));
  w       INT;
  v_qty   BIGINT;
  v_cov   BIGINT;
  v_do    TEXT := NULLIF(trim(COALESCE(p_do, '')), '');
  v_doid  BIGINT;
  v_cust  TEXT;
  v_by    TEXT;
  v_note  TEXT;
  pr      RECORD;
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  IF p_al IS NULL OR trim(p_al) = '' THEN RAISE EXCEPTION 'Name the customer order (AL).'; END IF;
  IF n1 IS NULL OR n2 IS NULL THEN RAISE EXCEPTION 'Key the first and the last seal.'; END IF;
  IF n2 < n1 THEN RAISE EXCEPTION 'The last seal is before the first. Key it from the smaller number.'; END IF;
  IF p_outcome NOT IN ('delivered', 'not_delivered') THEN RAISE EXCEPTION 'Say whether the seals were delivered.'; END IF;
  w := greatest(length(public.seal_digits(p_start)), length(public.seal_digits(COALESCE(NULLIF(trim(p_end), ''), p_start))));
  v_qty := n2 - n1 + 1;

  SELECT COALESCE(sum(LEAST(a.end_no, n2) - GREATEST(a.start_no, n1) + 1), 0), max(a.customer_name)
    INTO v_cov, v_cust
    FROM public.seal_allocations a
   WHERE a.al_number = p_al AND a.start_no <= n2 AND a.end_no >= n1;
  IF v_cov < v_qty THEN
    RAISE EXCEPTION 'Only % of these % seals were given to % on a consent.', v_cov, v_qty, p_al;
  END IF;
  IF EXISTS (SELECT 1 FROM public.fcportal_scan_records f
              WHERE f.al_number = p_al AND f.seal_no BETWEEN n1 AND n2) THEN
    RAISE EXCEPTION 'Some of these seals were scanned already. Key only the seals that were not scanned.';
  END IF;
  IF EXISTS (SELECT 1 FROM public.seal_settled_scans z
              WHERE z.al_number = p_al AND z.start_no <= n2 AND z.end_no >= n1) THEN
    RAISE EXCEPTION 'Some of these seals were settled already.';
  END IF;
  IF p_outcome = 'delivered' THEN
    IF v_do IS NULL THEN RAISE EXCEPTION 'Key the DO number these seals went out on.'; END IF;
    SELECT min(d.id) INTO v_doid FROM public.shared_do_records d
     WHERE d.do_number = v_do AND d.al_number = p_al;
    IF v_doid IS NULL THEN
      RAISE EXCEPTION 'DO % is not a DO of %. Check the DO number.', v_do, p_al;
    END IF;
  ELSE
    v_do := NULL;
  END IF;

  SELECT COALESCE(NULLIF(p.full_name, ''), p.email) INTO v_by
    FROM public.shared_profiles p WHERE p.id = auth.uid();
  v_by := COALESCE(v_by, 'Office');

  INSERT INTO public.seal_settled_scans
    (al_number, customer_name, start_code, end_code, start_no, end_no, outcome, do_number,
     remark, problem_id, settled_by, settled_by_id)
  VALUES
    (p_al, v_cust, public.seal_code(n1, w), public.seal_code(n2, w), n1, n2, p_outcome, v_do,
     NULLIF(trim(COALESCE(p_remark, '')), ''), p_problem, v_by, auth.uid());

  v_note := 'Seals ' || public.seal_code(n1, w) || ' - ' || public.seal_code(n2, w) || ' (' || v_qty || ') '
    || CASE WHEN p_outcome = 'delivered' THEN 'settled as delivered on DO ' || v_do
            ELSE 'settled as NOT delivered' END
    || ' by ' || v_by
    || COALESCE('. Remark: ' || NULLIF(trim(COALESCE(p_remark, '')), ''), '') || '.';

  FOR pr IN SELECT p.* FROM public.seal_problems p
             WHERE p.kind = 'missed_scan' AND p.status = 'open'
               AND (p.id = p_problem
                    OR (p.al_number = p_al AND public.seal_no(p.seal_from) >= n1 AND public.seal_no(p.seal_to) <= n2)) LOOP
    UPDATE public.seal_problems
       SET status = 'resolved', resolution = v_note, resolved_by = v_by, resolved_at = now()
     WHERE id = pr.id;
    PERFORM public.seal_close_case_if_done(pr.nelos_case_id, v_note, v_by);
  END LOOP;

  -- After the problem is settled, so the check the DO update sets off finds
  -- nothing left open and does not answer for the person who settled it.
  IF v_doid IS NOT NULL THEN
    UPDATE public.shared_do_records
       SET seal_ranges = COALESCE(CASE WHEN jsonb_typeof(seal_ranges) = 'array' THEN seal_ranges END, '[]'::JSONB)
                         || jsonb_build_array(jsonb_build_object('start', public.seal_code(n1, w),
                              'end', public.seal_code(n2, w), 'qty', v_qty, 'settled', true)),
           seal_qty = COALESCE(seal_qty, 0) + v_qty
     WHERE id = v_doid;
  END IF;

  RETURN v_note;
END $$;

-- The gaps for the page, each with the problem it raised.
DROP FUNCTION IF EXISTS public.seal_missed_scans();
CREATE FUNCTION public.seal_missed_scans()
RETURNS TABLE (al_number TEXT, customer_name TEXT, start_code TEXT, end_code TEXT, start_no BIGINT,
               end_no BIGINT, qty BIGINT, do_before TEXT, do_after TEXT, problem_id BIGINT, nelos_case_id BIGINT)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT public.seal_is_staff() THEN RAISE EXCEPTION 'Staff only'; END IF;
  RETURN QUERY
    SELECT f.al_number, f.customer_name, f.start_code, f.end_code, f.start_no, f.end_no, f.qty,
           f.do_before, f.do_after, p.id::BIGINT, p.nelos_case_id::BIGINT
      FROM public.seal_find_missed(NULL) f
      LEFT JOIN LATERAL (SELECT q.id, q.nelos_case_id FROM public.seal_problems q
                          WHERE q.kind = 'missed_scan' AND q.status = 'open' AND q.al_number = f.al_number
                            AND q.seal_from = f.start_code AND q.seal_to = f.end_code
                          ORDER BY q.id DESC LIMIT 1) p ON true
     ORDER BY f.al_number, f.start_no;
END $$;


-- ── 5. WHO MAY DO WHAT ───────────────────────────────────────────────────────
-- Staff read the settled rows. Nobody writes them except through
-- seal_settle_scan, which checks everything first.

ALTER TABLE public.seal_settled_scans ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS seal_settled_scans_read ON public.seal_settled_scans;
CREATE POLICY seal_settled_scans_read ON public.seal_settled_scans
  FOR SELECT TO authenticated USING (public.seal_is_staff());
GRANT SELECT ON public.seal_settled_scans TO authenticated;

REVOKE ALL ON FUNCTION public.seal_find_missed(TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.seal_flag_missed(TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.seal_close_case_if_done(BIGINT, TEXT, TEXT) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.seal_settle_scan(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, BIGINT) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.seal_missed_scans() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.seal_settle_scan(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.seal_missed_scans() TO authenticated;

